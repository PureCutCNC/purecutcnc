/**
 * Before/after record for the bundled example projects (#1192).
 *
 * Runs every example through the same loader and exporter the app uses —
 * `openProjectFromText` (so decode, migration and normalization are the real
 * ones) and the export preparation path with the inline executor (the app's
 * own `prepareExport` and `runPostProcessor`) — and records what a reader can
 * compare across a re-save:
 *
 * - the load warning (and machine-load diagnostics);
 * - the feature and operation counts;
 * - the posted G-code for every exportable operation, on the project's own
 *   machine or the bundled `generic` definition when it selects none.
 *
 * The G-code is stored as posted, plus a digest with the one clock-carrying
 * line (`Generated by PureCutCNC on YYYY-MM-DD`) collapsed, so two runs can be
 * compared without the date deciding the answer.
 *
 * Usage:
 *
 *   npx tsx scripts/resave-examples-check.ts before
 *   npx tsx scripts/resave-examples-check.ts after
 *   npx tsx scripts/resave-examples-check.ts before --examples-dir work/old-examples
 *
 * Writes `work/1192-<label>.json`. `--examples-dir` points the manifest and the
 * files at copies (for example `git show HEAD~:public/examples/...`) so the old
 * files can still be measured after the re-save has replaced them.
 */


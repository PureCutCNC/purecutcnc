import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { BUNDLED_DEFINITIONS, getActiveMachineDefinition } from '../src/engine/gcode/definitions'
import { validateMachineDefinition, type MachineDefinition } from '../src/engine/gcode/types'
import { createToolpathGenerationService } from '../src/app/toolpathGeneration/service'
import {
  createExportToken,
  prepareExport,
  type ExportPostOptions,
} from '../src/app/toolpathGeneration/exportPreparation'
import {
  listExportOperationOptions,
  type ExportOperationOption,
} from '../src/components/export/exportOperationSelection'
import { operationHiddenByProjectType } from '../src/store/helpers/projectType'
import { useProjectStore } from '../src/store/projectStore'
import type { Project } from '../src/types/project'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

interface ManifestEntry {
  id: string
  title: string
  description: string
  file: string
  thumbnail?: string
}

interface ProgramRecord {
  programNumber: number
  setupId: string | null
  setupName: string | null
  face: string
  fileStem: string
  operationIds: string[]
  gcode: string
  /** `gcode` with the generation date line collapsed to `<date>`. */
  gcodeSha256: string
  warnings: unknown[]
}

interface ExampleRecord {
  id: string
  file: string
  loadWarning: string | null
  machineDiagnostics: unknown[]
  featureCount: number
  operationCount: number
  featureFolderCount: number
  toolCount: number
  setupCount: number
  projectType: string | null
  selectedMachineId: string | null
  machineId: string
  machineSource: 'project' | 'default'
  exportOperationIds: string[]
  /** Operations the export carried G-code for, in project order. */
  postedOperationIds: string[]
  /** Why some operations produced no G-code; empty when the export covers all. */
  omittedOperations: OmittedOperation[]
  programs: ProgramRecord[]
}

/** Why an operation of the project did not reach any posted program. */
export type OmissionReason =
  /** The export checklist leaves it off: an Around setup of a non-rotary project. */
  | 'hidden-by-project-type'
  /** On the checklist, flagged not exportable because the operation is disabled. */
  | 'disabled'
  /** On the checklist, flagged not exportable because no existing tool is assigned. */
  | 'no-tool'
  /** On the checklist and exportable, but the postprocessor skipped it (other project type). */
  | 'not-posted'
  /** Neither posted nor on the checklist — the export route dropped it silently. */
  | 'not-listed'

export interface OmittedOperation {
  id: string
  name: string
  kind: string
  reason: OmissionReason
}

/**
 * Every project operation that produced no G-code, with the reason
 * (#1192 review finding 2).
 *
 * `listExportOperationOptions` filters out disabled, tool-less and
 * project-type-hidden operations, so exporting only its `exportable` entries
 * silently leaves those operations out. The handoff requires G-code for **all**
 * operations, so the record has to name what the run did not cover rather than
 * let the counts agree by omission.
 */
export function omittedOperations(
  project: Pick<Project, 'operations' | 'tools' | 'meta' | 'stock' | 'setups'>,
  options: readonly ExportOperationOption[],
  postedOperationIds: readonly string[],
): OmittedOperation[] {
  const posted = new Set(postedOperationIds)
  const optionById = new Map(options.map((option) => [option.operation.id, option]))
  return project.operations.flatMap((operation) => {
    if (posted.has(operation.id)) return []
    const option = optionById.get(operation.id)
    const reason: OmissionReason = operationHiddenByProjectType(project, operation)
      ? 'hidden-by-project-type'
      : option === undefined
        ? 'not-listed'
        : option.exportable
          ? 'not-posted'
          : operation.enabled
            ? 'no-tool'
            : 'disabled'
    return [{ id: operation.id, name: operation.name, kind: operation.kind, reason }]
  })
}

interface CheckArguments {
  label: 'before' | 'after'
  examplesDir: string
}

/** Parse `<before|after> [--examples-dir <dir>]`; exported so the test also pins the CLI contract. */
export function parseArguments(argv: readonly string[]): CheckArguments {
  const examplesDirFlag = argv.indexOf('--examples-dir')
  const examplesDirOverride = examplesDirFlag >= 0 ? argv[examplesDirFlag + 1] : undefined
  const label = argv.find((argument, index) => (
    !argument.startsWith('-') && (examplesDirFlag < 0 || index !== examplesDirFlag + 1)
  ))
  if (label !== 'before' && label !== 'after') {
    throw new Error('usage: npx tsx scripts/resave-examples-check.ts <before|after> [--examples-dir <dir>]')
  }
  if (examplesDirFlag >= 0 && examplesDirOverride === undefined) {
    throw new Error('--examples-dir needs a directory')
  }
  return {
    label,
    examplesDir: examplesDirOverride ? resolve(examplesDirOverride) : join(root, 'public/examples'),
  }
}

const DATE_LINE = /Generated by PureCutCNC on \d{4}-\d{2}-\d{2}/g

function digestOfProgram(gcode: string): string {
  return createHash('sha256').update(gcode.replace(DATE_LINE, 'Generated by PureCutCNC on <date>')).digest('hex')
}

function defaultMachine(): MachineDefinition {
  const generic = BUNDLED_DEFINITIONS.find((definition) => definition.id === 'generic')
  if (!generic) throw new Error('bundled generic machine is missing')
  return validateMachineDefinition(structuredClone(generic))
}

async function record(entry: ManifestEntry, examplesDir: string): Promise<ExampleRecord> {
  const text = readFileSync(join(examplesDir, entry.file), 'utf8')
  useProjectStore.getState().openProjectFromText(text, null)
  const state = useProjectStore.getState()
  const project: Project = state.project

  const selected = getActiveMachineDefinition(project)
  const definition = selected ?? defaultMachine()
  const machineSource: 'project' | 'default' = selected ? 'project' : 'default'

  // The same exportable set the Export dialog lists, in project order — which
  // is the order they are cut in.
  const exportOptions = listExportOperationOptions(project)
  const exportOperationIds = exportOptions
    .filter((option) => option.exportable)
    .map((option) => option.operation.id)

  const options: ExportPostOptions = {
    emitToolChanges: true,
    emitCoolant: false,
    programName: project.meta.name,
    captureMotionTrace: false,
  }
  const context = { project, documentKey: state.projectKey }
  const service = createToolpathGenerationService({ getCurrentContext: () => context })
  try {
    const token = createExportToken(1, context, exportOperationIds, definition, options)
    const preparation = await prepareExport(service, context, token, definition, options)
    if (preparation.status !== 'ready') {
      const why = preparation.status === 'blocked' ? JSON.stringify(preparation.reason) : preparation.status
      throw new Error(`export preparation for ${entry.file} was ${preparation.status}: ${why}`)
    }
    const programs: ProgramRecord[] = preparation.programs.map((program) => ({
      programNumber: program.programNumber,
      setupId: program.setupId,
      setupName: program.setupName,
      face: program.face,
      fileStem: program.fileStem,
      operationIds: program.operations.map((operation) => operation.operation.id),
      gcode: program.result.gcode,
      gcodeSha256: digestOfProgram(program.result.gcode),
      warnings: program.result.warnings,
    }))

    const postedOperationIds = programs.flatMap((program) => program.operationIds)

    return {
      id: entry.id,
      file: entry.file,
      loadWarning: state.loadWarning,
      machineDiagnostics: state.machineLoadDiagnostics,
      featureCount: project.features.length,
      operationCount: project.operations.length,
      featureFolderCount: project.featureFolders.length,
      toolCount: project.tools.length,
      setupCount: project.setups?.length ?? 0,
      projectType: project.meta.projectType ?? null,
      selectedMachineId: project.meta.selectedMachineId ?? null,
      machineId: definition.id,
      machineSource,
      exportOperationIds,
      postedOperationIds,
      omittedOperations: omittedOperations(project, exportOptions, postedOperationIds),
      programs,
    }
  } finally {
    service.dispose()
  }
}

const OMISSION_HINTS: Record<OmissionReason, string> = {
  'hidden-by-project-type': 'not on the export checklist (Around setup of a non-rotary project)',
  disabled: 'on the checklist but disabled',
  'no-tool': 'on the checklist but its tool is missing',
  'not-posted': 'on the checklist but the postprocessor skipped it',
  'not-listed': 'neither posted nor on the export checklist',
}

async function main(): Promise<void> {
  const { label, examplesDir } = parseArguments(process.argv.slice(2))
  const manifest = JSON.parse(readFileSync(join(examplesDir, 'manifest.json'), 'utf8')) as ManifestEntry[]
  const examples: ExampleRecord[] = []
  for (const entry of manifest) {
    const recordForEntry = await record(entry, examplesDir)
    examples.push(recordForEntry)
    const warnings = recordForEntry.loadWarning ? ` warnings: ${recordForEntry.loadWarning}` : ' warnings: none'
    const omitted = recordForEntry.omittedOperations.length === 0
      ? 'all operations posted'
      : `${recordForEntry.omittedOperations.length} operation(s) NOT posted: ` +
        recordForEntry.omittedOperations.map((operation) => `${operation.name} (${operation.reason})`).join(', ')
    console.log(
      `${entry.file}: ${recordForEntry.featureCount} features, ${recordForEntry.operationCount} operations, ` +
      `${recordForEntry.postedOperationIds.length} posted across ${recordForEntry.programs.length} program(s) on ` +
      `${recordForEntry.machineId}` +
      `${recordForEntry.machineSource === 'default' ? ' (default machine)' : ''}, ${omitted}${warnings}`,
    )
  }

  const snapshot = {
    label,
    examplesDir,
    recordedAt: new Date().toISOString(),
    examples,
  }
  mkdirSync(join(root, 'work'), { recursive: true })
  const outPath = join(root, 'work', `1192-${label}.json`)
  writeFileSync(outPath, JSON.stringify(snapshot, null, 2))
  console.log(`wrote ${outPath}`)

  // The record above is written even when it finds a gap, so the snapshot can
  // still be inspected. The gap itself is a failure: the handoff requires
  // G-code for all operations, and the old check's silent filter is exactly how
  // an operation went unmeasured (#1192 review finding 2).
  const omissions = examples.flatMap((example) => (
    example.omittedOperations.map((operation) => ({ file: example.file, operation }))
  ))
  if (omissions.length > 0) {
    console.error(`coverage: ${omissions.length} operation(s) produced no G-code:`)
    for (const { file, operation } of omissions) {
      console.error(`  ${file}: ${operation.name} [${operation.kind}] (${operation.id}) — ${OMISSION_HINTS[operation.reason]}`)
    }
    throw new Error(`the export does not cover every operation (${omissions.length} omitted); see the list above`)
  }
}

const invokedDirectly = process.argv[1] !== undefined
  && resolve(process.argv[1]) === fileURLToPath(import.meta.url)

if (invokedDirectly) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error)
    process.exit(1)
  })
}

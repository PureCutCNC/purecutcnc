/**
 * Rotary generation probe (#1115 slice p-a). A diagnostic, not a quality gate.
 *
 * #1050 made generation around the bar measurably slower. Optimising it means
 * changing engine code, and the first thing such a change must not do is move
 * the toolpath: the approved decision for #1115 is that output stays
 * byte-identical — same moves, same posted program — while each around rotary
 * operation comes back within 1.5x its pre-#1050 generation time. A suite that
 * asserts what its author expected cannot prove either half against the real
 * benchmark files, so this probe measures the pair together:
 *
 *   - **time**, per operation: one cold run and five warm forced
 *     regenerations, timed around the engine entry alone — never around
 *     loading, simulation or posting;
 *   - **identity**, per operation: the fixture's SHA-256, the operation's id,
 *     kind, axis, tool, feeds and settings, a digest of the generated moves,
 *     and a digest of the posted program with the date line normalised.
 *
 * The engine entry is `computeOperationToolpath` — the same one the app's
 * worker calls (`generateOperation.ts` is the single synchronous entry point,
 * issue #675), so these are the app's numbers and not an adjacent path's.
 *
 * `--root <checkout>` measures another checkout's engine through a dynamic
 * import from that tree, which is how the pre-#1050 reference at
 * `…/worktrees/purecutcnc/ref-pre-1050` is timed. The pre-#1050 tree exposes
 * the same four functions this probe needs (`normalizeProject`,
 * `computeOperationToolpath`, `normalizeToolForProject`, `runPostProcessor`),
 * so no adapter is used; `loadEngineTree` fails loudly if that ever stops being
 * true.
 *
 * `--baseline <json>` compares a run with a stored baseline and fails on any
 * identity mismatch (fixture hash, stock and per-operation rotation axis,
 * operation id or settings) or any move or program digest difference. Later
 * #1115 slices keep the head baseline at `work/1115-baseline.json` and run this
 * option against their own engine, so a change that merely looks identical
 * cannot pass.
 *
 * Two guards keep the instrument honest about what it measures: `--out` may
 * not name the fixture (or a symlink/hardlink to it) — the probe never
 * overwrites its own input — and the program digest collapses the generator's
 * own `Generated by PureCutCNC on <date>` header line and nothing else. The
 * stamp is found by the date the post stamped (read either side of the call)
 * *minus the program-name line*, which is identified by its words rather than
 * by its date: every definition writes the program name first, and a project
 * named `Generated by PureCutCNC on <date>` puts a lookalike above the real
 * stamp — or, on the day it names, a line byte-identical to it. Collapsing the
 * first lookalike hid the name; collapsing every date-carrying line hid a name
 * that happened to carry the generation date, so the same output hashed one way
 * on that day and another way the next. A date that is not the generation date
 * — the name's, a job note's, a stamp-shaped comment's — is program text and
 * still moves the hash.
 *
 * `--async` measures the same operations through the asynchronous rotary driver
 * (#1115 slice p-d1): `computeOperationToolpathAsync`, which runs the batch
 * through its in-process serial runner. The report's `engine.entry` says which
 * entry produced the numbers, and every baseline check is unchanged, so a run
 * on the async path either matches the stored baseline exactly or fails.
 *
 * `--workers <n>` measures the same operations through the **angle worker pool**
 * (#1115 slice p-d2): the asynchronous entry with a `RotaryBatchFactory` that
 * samples each batch on `n` Node `worker_threads` workers, capped by the pool's
 * own eight-worker ceiling, its cores-minus-two reservation and its 512 MiB
 * typed-buffer budget (which the run reports, so a request for eight workers and
 * the three that fit are told apart). Each run records the per-phase split --
 * worker install, wall time awaiting replies, batches, plan revisions -- and the
 * process's peak RSS, so what stays serial is measured rather than assumed.
 * `--pool-budget-mb <n>` raises that budget for a benchmark that needs to see the
 * uncapped ceiling.
 *
 * `--pass-direction <around|along>` builds a pass-direction control in memory:
 * the selected operations are copied with `rotaryPassDirection` changed after
 * the fixture is loaded and never written back. The handoff forbids saving a
 * modified copy of a benchmark, so the control's fixture hash is the original
 * file's hash and proves the file itself was not touched.
 *
 * Posting needs a machine definition, and the benchmark projects name none
 * (`meta.selectedMachineId` is null). The probe therefore attaches a
 * documented baseline machine — bundled `grbl` plus an own-drive rotary block
 * about the stock's own axis — and records that it did. The program's *text*
 * is not the point of the hash; its stability across slices is.
 *
 * Usage:
 *   npx tsx scripts/rotary-generation-probe.ts --project <file.camj> --operation <id> [--operation <id>…]
 *       [--pass-direction <around|along>] [--async] [--workers <n>] [--pool-budget-mb <n>]
 *       [--out <json>] [--root <checkout>] [--baseline <json>]
 *
 * The result JSON defaults to `work/rotary-generation-probe.json` in this
 * checkout. Nothing is ever written back to the fixture.
 */


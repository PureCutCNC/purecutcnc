// ── the measured checkout's engine ───────────────────────────

/** The four functions this probe needs, typed by our own tree's declarations. */
interface EngineTree {
  root: string
  commit: string | null
  normalizeProject(input: unknown): Project
  computeOperationToolpath(
    project: Project,
    operation: Operation,
    options?: { trace?: boolean },
  ): { result: ToolpathResult } | null
  /**
   * The asynchronous rotary entry (#1115 slice p-d1), where the measured
   * checkout has one. Optional because `--root` may name an older tree -- the
   * pre-#1050 reference, for one -- that predates it.
   */
  computeOperationToolpathAsync?(
    project: Project,
    operation: Operation,
    options?: { trace?: boolean; rotaryRunBatch?: RotaryBatchFactory },
  ): Promise<{ result: ToolpathResult } | null>
  normalizeToolForProject(tool: Tool, project: Project): NormalizedTool
  runPostProcessor(input: PostProcessorInput): PostProcessorResult
  validateMachineDefinition(raw: unknown): MachineDefinition
  bundledDefinitions: MachineDefinition[]
}

/**
 * Load a checkout's engine through dynamic imports from its own tree.
 *
 * A static import would bind this probe's checkout forever, which is the one
 * thing `--root` exists to escape. Every module is imported by absolute file
 * URL, so the reference tree resolves its own dependencies from its own
 * `node_modules`.
 */
export async function loadEngineTree(root: string): Promise<EngineTree> {
  const load = async <T>(path: string): Promise<T> => {
    const url = pathToFileURL(join(root, path)).href
    try {
      return (await import(url)) as T
    } catch (error) {
      throw new ProbeError(
        `cannot load ${path} from ${root}: ${error instanceof Error ? error.message : String(error)}`,
      )
    }
  }

  const projectFormat = await load<{ normalizeProject(input: unknown): Project }>(
    'src/store/helpers/projectFormat.ts',
  )
  const generation = await load<{
    computeOperationToolpath(
      project: Project,
      operation: Operation,
      options?: { trace?: boolean },
    ): { result: ToolpathResult } | null
    computeOperationToolpathAsync?(
      project: Project,
      operation: Operation,
      options?: { trace?: boolean; rotaryRunBatch?: RotaryBatchFactory },
    ): Promise<{ result: ToolpathResult } | null>
  }>('src/engine/toolpaths/generateOperation.ts')
  const geometry = await load<{ normalizeToolForProject(tool: Tool, project: Project): NormalizedTool }>(
    'src/engine/toolpaths/geometry.ts',
  )
  const postprocessor = await load<{
    runPostProcessor(input: PostProcessorInput): PostProcessorResult
  }>('src/engine/gcode/postprocessor.ts')
  const types = await load<{ validateMachineDefinition(raw: unknown): MachineDefinition }>(
    'src/engine/gcode/types.ts',
  )
  const definitions = await load<{ BUNDLED_DEFINITIONS: MachineDefinition[] }>(
    'src/engine/gcode/definitions/index.ts',
  )

  for (const [name, value] of [
    ['normalizeProject', projectFormat.normalizeProject],
    ['computeOperationToolpath', generation.computeOperationToolpath],
    ['normalizeToolForProject', geometry.normalizeToolForProject],
    ['runPostProcessor', postprocessor.runPostProcessor],
    ['validateMachineDefinition', types.validateMachineDefinition],
  ] as const) {
    if (typeof value !== 'function') {
      throw new ProbeError(`${root} does not export ${name}; the probe needs a checkout with this API`)
    }
  }
  if (!Array.isArray(definitions.BUNDLED_DEFINITIONS)) {
    throw new ProbeError(`${root} does not export BUNDLED_DEFINITIONS; the probe needs a checkout with this API`)
  }

  return {
    root,
    commit: engineCommit(root),
    normalizeProject: projectFormat.normalizeProject,
    computeOperationToolpath: generation.computeOperationToolpath,
    ...(typeof generation.computeOperationToolpathAsync === 'function'
      ? { computeOperationToolpathAsync: generation.computeOperationToolpathAsync }
      : {}),
    normalizeToolForProject: geometry.normalizeToolForProject,
    runPostProcessor: postprocessor.runPostProcessor,
    validateMachineDefinition: types.validateMachineDefinition,
    bundledDefinitions: definitions.BUNDLED_DEFINITIONS,
  }
}

/** The measured checkout's HEAD, or null when it is not a git checkout. */
function engineCommit(root: string): string | null {
  try {
    return execFileSync('git', ['-C', root, 'rev-parse', '--short', 'HEAD'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim()
  } catch {
    return null
  }
}

// ── argument parsing and operation selection ─────────────────

export interface ProbeDefaults {
  out: string
  root: string
}

/**
 * Parse argv (already sliced past the script name).
 *
 * Strict on purpose: a mistyped flag or a missing value must not silently
 * measure the default checkout with the default output path, because the
 * timings look plausible either way.
 */
export function parseProbeArgs(argv: readonly string[], defaults: ProbeDefaults): ProbeArgs {
  let project: string | null = null
  const operations: string[] = []
  let out = defaults.out
  let root = defaults.root
  let baseline: string | null = null
  let passDirection: PassDirection | null = null
  let rotaryAsync = false
  let workers: number | null = null
  let poolBudgetMb: number | null = null

  for (let index = 0; index < argv.length; index += 1) {
    const flag = argv[index]
    const value = () => {
      const next = argv[index + 1]
      if (next === undefined || next.startsWith('--')) {
        throw new ProbeError(`${flag} needs a value`)
      }
      index += 1
      return next
    }
    switch (flag) {
      case '--project':
        project = value()
        break
      case '--operation': {
        const id = value()
        if (!operations.includes(id)) operations.push(id)
        break
      }
      case '--out':
        out = value()
        break
      case '--root':
        root = value()
        break
      case '--baseline':
        baseline = value()
        break
      case '--async':
        rotaryAsync = true
        break
      case '--workers': {
        const text = value()
        const parsed = Number(text)
        if (!Number.isInteger(parsed) || parsed < 1) {
          throw new ProbeError(`--workers needs a positive whole number of workers; got ${text}`)
        }
        workers = parsed
        break
      }
      case '--pool-budget-mb': {
        const text = value()
        const parsed = Number(text)
        if (!Number.isFinite(parsed) || parsed < 1) {
          throw new ProbeError(`--pool-budget-mb needs a positive number of MiB; got ${text}`)
        }
        poolBudgetMb = parsed
        break
      }
      case '--pass-direction': {
        const direction = value()
        if (!isPassDirection(direction)) {
          throw new ProbeError(
            `--pass-direction must be one of ${PASS_DIRECTIONS.join(', ')}; got ${direction}`,
          )
        }
        passDirection = direction
        break
      }
      default:
        throw new ProbeError(`unknown argument ${flag}`)
    }
  }

  if (project === null) throw new ProbeError('--project <file.camj> is required')
  if (operations.length === 0) throw new ProbeError('--operation <id> is required at least once')
  return {
    project: resolve(project),
    operations,
    out: resolve(out),
    root: resolve(root),
    baseline: baseline === null ? null : resolve(baseline),
    passDirection,
    // `--workers` measures the asynchronous entry by definition: the pool is a
    // batch runner for that driver, so the flag selects it too.
    rotaryAsync: rotaryAsync || workers !== null,
    workers,
    poolBudgetMb,
  }
}

/**
 * The operations named by id, in the order given.
 *
 * A missing id is a mistyped fixture, not an empty measurement: the message
 * names every operation the file does have, because "op0021 not found" is
 * useless when the file says op0025.
 */
export function selectOperations<T extends { id: string; name?: string }>(
  project: { operations: readonly T[] },
  ids: readonly string[],
): T[] {
  const available = project.operations.map((operation) => operation.id)
  const selected: T[] = []
  for (const id of ids) {
    const operation = project.operations.find((candidate) => candidate.id === id)
    if (!operation) {
      const list = available.length === 0 ? '(none)' : available.join(', ')
      throw new ProbeError(`operation ${id} is not in the project; available operations: ${list}`)
    }
    selected.push(operation)
  }
  return selected
}

/**
 * Whether an operation is one whose passes have a direction.
 *
 * Spelled out here rather than imported from the measured tree so the engine
 * import stays the probe's only runtime link to it: a fixture is normalized by
 * the measured checkout, while this predicate has to read the same on any tree.
 */
function isRotaryOperation(operation: Operation): boolean {
  return operation.kind === 'rotary_rough' || operation.kind === 'rotary_finish'
}

/**
 * The selected operations with their pass direction changed, as copies.
 *
 * This is how a pass-direction control is built after #1115's fixture rule: a
 * benchmark `.camj` is read as saved and never rewritten, so an along control
 * cannot be a second file on disk. The engine entry takes the operation as an
 * argument (`computeOperationToolpath(project, operation)`), so changing the
 * copy is enough — the loaded project keeps its own record untouched, and the
 * report's fixture hash still names the file that was measured.
 */
export function withPassDirection(
  operations: readonly Operation[],
  direction: PassDirection,
): Operation[] {
  return operations.map((operation) => {
    if (!isRotaryOperation(operation)) {
      throw new ProbeError(
        `operation ${operation.id} is not a rotary operation, so --pass-direction cannot build a control from it`,
      )
    }
    return { ...operation, rotaryPassDirection: direction }
  })
}

/**
 * The real file a path names, for comparison against another path.
 *
 * The output usually does not exist yet, so fall back to the real directory
 * plus the file's own name: a symlinked directory then still resolves to the
 * fixture's directory even though the resolved string differs.
 */
function canonicalPath(path: string): string {
  try {
    return realpathSync(path)
  } catch {
    try {
      return join(realpathSync(dirname(path)), basename(path))
    } catch {
      return resolve(path)
    }
  }
}

/**
 * Whether two paths name the same file: the same path, the same file reached
 * through a symlink, or the same inode through a hardlink.
 */
export function pathsAlias(left: string, right: string): boolean {
  if (canonicalPath(left) === canonicalPath(right)) return true
  try {
    const leftStat = statSync(left)
    const rightStat = statSync(right)
    return leftStat.dev === rightStat.dev && leftStat.ino === rightStat.ino
  } catch {
    return false
  }
}

/**
 * Refuse an output path that would write over the fixture being measured.
 *
 * Checked before anything is loaded or generated, because a run that measures
 * the fixture and then replaces it has destroyed the benchmark it just read —
 * and the replacement looks like a normal result file.
 */
export function assertOutputIsNotFixture(out: string, fixture: string): void {
  if (pathsAlias(out, fixture)) {
    throw new ProbeError(
      `--out ${out} is the fixture ${fixture}; the probe reads its input and never writes it`,
    )
  }
}

// ── digests ──────────────────────────────────────────────────
/** SHA-256 of bytes or text, hex. */
export function sha256(data: string | Uint8Array): string {
  return createHash('sha256').update(data).digest('hex')
}

/**
 * JSON with object keys sorted, so two equal settings objects always digest
 * the same whatever order they were built in.
 */
export function stableStringify(value: unknown): string {
  if (Array.isArray(value)) {
    return `[${value.map((entry) => stableStringify(entry)).join(',')}]`
  }
  if (value !== null && typeof value === 'object') {
    const record = value as Record<string, unknown>
    const entries = Object.keys(record)
      .sort()
      .filter((key) => record[key] !== undefined)
      .map((key) => `${JSON.stringify(key)}:${stableStringify(record[key])}`)
    return `{${entries.join(',')}}`
  }
  const serialized = JSON.stringify(value)
  return serialized === undefined ? 'null' : serialized
}

/** One line per move: everything that decides where the tool goes and how fast. */
function moveLine(move: ToolpathResult['moves'][number]): string {
  const point = (value: { x: number; y: number; z: number; a?: number }): string =>
    [value.x, value.y, value.z, value.a ?? ''].join(',')
  return [move.kind, point(move.from), point(move.to), move.source ?? '', move.feedScale ?? ''].join('|')
}

/** A digest of every generated move; `a` (the bar's angle) included. */
export function digestMoves(moves: readonly ToolpathResult['moves'][number][]): string {
  return sha256(moves.map((move) => moveLine(move)).join('\n'))
}

/**
 * A stamp-shaped header line: optional line number, comment introducer, the
 * payload `Generated by PureCutCNC on <date>`, then — for the parenthesised
 * dialects — the closing paren and any trailing spaces.
 *
 * Captures: 1 the prefix through the comment introducer, 2 the payload's fixed
 * words (the part a project name is written as), 3 the date, 4 the padding,
 * 5 the closing paren with its leading spaces.
 *
 * The line's own terminator is part of capture 4: the ShopBot part file is
 * written with CRLF line endings (`SBP_LINE_ENDING`), so splitting on `\n`
 * leaves a `\r` on every line. Anchoring on `[ \t]*$` alone rejected all of
 * them, which meant nothing collapsed in a real `.sbp` program and its digest
 * named the day.
 */
const STAMP_LINE =
  /^((?:N\d+[ \t]+)?[ \t]*(?:;[ \t]*|\([ \t]*|'[ \t]*))(Generated by PureCutCNC on )(\d{4}-\d{2}-\d{2})(([ \t]*\))?[ \t]*\r?)$/

/** One line carrying the generation date, split into what identifies it. */
interface StampCandidate {
  index: number
  /** What the comment says, without a closing paren — a name line's project name. */
  payload: string
  /** The comment's whole body, closing paren included — the name as that dialect writes it. */
  body: string
  /** Everything before the date, so the collapsed line keeps its dialect. */
  prefix: string
  /** Everything after the date: closing paren and padding. */
  suffix: string
}

function stampCandidates(lines: readonly string[], dates: ReadonlySet<string>): StampCandidate[] {
  const candidates: StampCandidate[] = []
  lines.forEach((line, index) => {
    const match = STAMP_LINE.exec(line)
    if (!match || !dates.has(match[3])) return
    const payload = `${match[2]}${match[3]}`
    candidates.push({
      index,
      payload,
      body: `${payload}${match[5] ?? ''}`,
      prefix: `${match[1]}${match[2]}`,
      suffix: match[4],
    })
  })
  return candidates
}

/**
 * The program name as a post writes it, one form per sanitizer it can pass
 * through.
 *
 * Operator text never reaches the program verbatim. The G-code postprocessor
 * trims it, collapses its whitespace, and removes the comment markers that
 * would end the comment (`(`, `)`, `;`, and `'` for a definition that comments
 * with an apostrophe); the ShopBot emitter only trims and collapses. So a
 * project called `Generated by PureCutCNC on 2026-11-01 ` is *written* as
 * `Generated by PureCutCNC on 2026-11-01`, and identifying the name line by
 * the project's own spelling missed it: on the day the name and the stamp
 * matched, both looked like the stamp, while on any other day only the stamp
 * did — the same output hashed one way that day and another way the next.
 *
 * Every form returned is what some bundled emitter would write, so matching
 * any of them identifies a line as the name whatever wrote it. An empty name
 * yields no form and therefore no name line, as before.
 */
function emittedNameForms(programName: string): Set<string> {
  const collapse = (text: string): string => text.replace(/\s+/g, ' ').trim()
  const forms = [
    // The ShopBot emitter (`commentText`), and a G-code name with no marker.
    collapse(programName),
    // The G-code postprocessor (`safeCommentText`) with a `;` or `(` dialect.
    collapse(programName.replace(/[();]/g, ' ')),
    // The same with an apostrophe-comment dialect (`commentPrefix` `'`).
    collapse(programName.replace(/[();']/g, ' ')),
  ]
  return new Set(forms.filter((form) => form !== ''))
}

/**
 * The program as posted, with the generator's own header date collapsed.
 *
 * `generatedOn` is the ISO date the postprocessor stamped the program with —
 * normally one value, two only for a post that crosses midnight. `programName`
 * is the project name the post wrote as the program's name; it identifies the
 * name line by its *words*, independently of the date, and is required because
 * a name and the stamp can otherwise be the same line of text. It is compared
 * as the post *emitted* it (`emittedNameForms`), not as the project spells it:
 * operator text is trimmed and stripped of comment markers on the way out.
 *
 * Every bundled definition writes `{programName}` *before* the generated date
 * (GRBL: `; {programName}` then `; Generated by PureCutCNC on {date}`, and the
 * OpenSBP emitter the same), so a project called
 * `Generated by PureCutCNC on 2020-01-01` puts a whole stamp-shaped line in the
 * program that is *not* the stamp. Two earlier defects lived here:
 *
 *   - collapsing the *first* lookalike collapsed that name, leaving the real
 *     stamp carrying today's date — a renamed project left the hash unchanged
 *     and tomorrow's run moved it;
 *   - collapsing every date-carrying stamp-shaped line still normalized the
 *     name whenever the name's date happened to equal the generation date — a
 *     project named `Generated by PureCutCNC on 2026-11-01` hashed one way on
 *     the 1st and another way on the 2nd, because only the real stamp collapsed
 *     on the 2nd. A post crossing midnight has two generation dates, so the
 *     same window could hide a rename between them.
 *
 * So the name line is never collapsed: a stamp-shaped line whose payload (or
 * whole body, for a name written with its closing paren) is the emitted
 * project name is program text. Only when *every* date-carrying stamp-shaped
 * line is the name — the project is called that day's stamp, so the name and
 * the stamp are byte-identical — is one of them the stamp, and the first is the
 * name, so the rest collapse. That keeps day one's hash equal to day two's.
 *
 * The caller supplies the date instead of this function reading the clock, so
 * two runs of the same output hash the same whatever day they are made on and
 * the tests are not time-dependent.
 *
 * Everything else is program text that a later edit may legitimately change
 * and must move the hash. `STAMP_LINE` is whole-line and anchored, so
 *
 *   - the stamp inside an ordinary comment (`; job note: Generated by
 *     PureCutCNC on 2020-01-01`) is left alone — an unanchored match hid it;
 *   - a stamp-shaped comment carrying another date is left alone, wherever it
 *     sits;
 *   - a date-shaped string elsewhere (`drawn 2026-11-01`) is left alone.
 *
 * A line of program text that reproduces the generated stamp byte for byte is
 * indistinguishable from a second stamp and collapses with it. A custom machine
 * definition that renders the date some other way (or a line-numbered header in
 * a dialect not covered by the optional `N` prefix) is not normalized here; its
 * digest then names the day, which is a visible finding rather than a silent
 * blind spot.
 *
 * The program's own line endings are preserved: a CRLF ShopBot part file
 * normalizes to itself with the date replaced, not to its LF twin.
 */
export function normalizeProgramDate(
  program: string,
  generatedOn: string | readonly string[],
  programName: string,
): string {
  const dates = new Set(typeof generatedOn === 'string' ? [generatedOn] : generatedOn)
  const lines = program.split('\n')
  const candidates = stampCandidates(lines, dates)
  const names = emittedNameForms(programName)
  const isNameLine = (candidate: StampCandidate): boolean =>
    names.has(candidate.payload) || names.has(candidate.body)
  const nameLines = candidates.filter(isNameLine)
  const stamps = candidates.filter((candidate) => !isNameLine(candidate))
  // The stamp is every date-carrying line that is not the name. When the name
  // is byte-identical to that day's stamp there is no such line, and the name —
  // written above the stamp by every bundled definition — is the first.
  const collapsing = stamps.length > 0 ? stamps : nameLines.slice(1)
  const collapsed = new Map<number, string>()
  for (const candidate of collapsing) {
    collapsed.set(candidate.index, `${candidate.prefix}<date>${candidate.suffix}`)
  }
  return lines.map((line, index) => collapsed.get(index) ?? line).join('\n')
}

/** A digest of the posted program with the generation date collapsed. */
export function digestProgram(
  program: string,
  generatedOn: string | readonly string[],
  programName: string,
): string {
  return sha256(normalizeProgramDate(program, generatedOn, programName))
}

// ── measuring ────────────────────────────────────────────────

function roundMs(value: number): number {
  return Math.round(value * 10) / 10
}

export function median(values: readonly number[]): number {
  if (values.length === 0) throw new ProbeError('median of no values')
  const sorted = [...values].sort((left, right) => left - right)
  const middle = Math.floor(sorted.length / 2)
  return sorted.length % 2 === 1 ? sorted[middle] : (sorted[middle - 1] + sorted[middle]) / 2
}

/** The machine a program is posted with, and why it was chosen. */
function postMachine(
  tree: EngineTree,
  project: Project,
): { definition: MachineDefinition; id: string; source: 'project' | 'probe-baseline' } {
  const selectedId = project.meta.selectedMachineId
  if (selectedId) {
    const stored = project.meta.machineDefinitions.find((definition) => definition.id === selectedId)
    if (!stored) {
      throw new ProbeError(`the project selects machine ${selectedId}, which it does not carry`)
    }
    return { definition: tree.validateMachineDefinition(stored), id: selectedId, source: 'project' }
  }

  const base = tree.bundledDefinitions.find((definition) => definition.id === BASELINE_MACHINE_BASE)
  if (!base) {
    throw new ProbeError(`${tree.root} bundles no ${BASELINE_MACHINE_BASE} machine definition to post with`)
  }
  const shape = project.stock.shape
  const about = (shape === 'round' || shape === 'square') && project.stock.axis ? project.stock.axis : 'x'
  const definition = tree.validateMachineDefinition({
    ...structuredClone(base),
    rotary: { about, drive: 'own', reversed: false, inverseTimeFeed: { on: 'G93', off: 'G94' } },
  })
  return { definition, id: `${base.id}+${about}-rotary`, source: 'probe-baseline' }
}

function toolFor(tree: EngineTree, project: Project, operation: Operation): NormalizedTool {
  const record = operation.toolRef
    ? project.tools.find((tool) => tool.id === operation.toolRef)
    : null
  if (!record) {
    throw new ProbeError(`operation ${operation.id} has no tool, so its output has no meaning to hash`)
  }
  return tree.normalizeToolForProject(record, project)
}

function stockAxis(project: Project): string | null {
  const shape = project.stock.shape
  return shape === 'round' || shape === 'square' ? project.stock.axis ?? null : null
}

/** Today in the postprocessor's own stamp format (`YYYY-MM-DD`, UTC). */
function generationDate(): string {
  return new Date().toISOString().slice(0, 10)
}

/**
 * Memory and phase readings after one generation run (#1115 slice p-d2).
 *
 * `maxRSS` is the **process** high-water mark, and under `worker_threads` the
 * workers are threads of that process, so it covers their heaps too. It only
 * ever rises, so a run's reading is at least every earlier run's; a benchmark
 * that wants one configuration's peak runs it in its own process, which is what
 * the p-d2 benchmark does.
 */
function runDetail(pools: readonly RotaryAnglePool[], totalMs: number): RunDetail {
  const usage = process.resourceUsage()
  const toMiB = (bytes: number): number => Math.round((bytes / 1048576) * 10) / 10
  const detail: RunDetail = {
    totalMs: roundMs(totalMs),
    installMs: 0,
    awaitMs: 0,
    batches: 0,
    planRevisions: 0,
    rejectedReplies: 0,
    workers: 0,
    mode: 'serial',
    fallback: 'none',
    setupBytesPerWorker: 0,
    rssMiB: toMiB(process.memoryUsage().rss),
    rssPeakMiB: toMiB(usage.maxRSS * 1024),
  }
  let installMs = 0
  let awaitMs = 0
  let batches = 0
  let planRevisions = 0
  let rejectedReplies = 0
  let workers = 0
  let fallback: RunDetail['fallback'] = 'none'
  for (const pool of pools) {
    const stats = pool.stats()
    installMs += stats.installMs
    awaitMs += stats.awaitMs
    batches += stats.batches
    planRevisions += stats.planRevisions
    rejectedReplies += stats.rejectedReplies
    workers = Math.max(workers, stats.workers)
    if (stats.fallback !== 'none') fallback = stats.fallback
    detail.mode = stats.mode
    detail.setupBytesPerWorker = Math.max(detail.setupBytesPerWorker, stats.setupBytes)
  }
  return {
    ...detail,
    installMs: Math.round(installMs * 10) / 10,
    awaitMs: Math.round(awaitMs * 10) / 10,
    batches,
    planRevisions,
    rejectedReplies,
    workers,
    fallback,
    // Without a pool, the run is serial by construction: the in-process runner
    // owns no phase of its own.
    mode: pools.length > 0 ? detail.mode : 'serial',
  }
}

async function operationReport(
  tree: EngineTree,
  project: Project,
  operation: Operation,
  args: Pick<ProbeArgs, 'rotaryAsync' | 'workers' | 'poolBudgetMb'>,
): Promise<OperationReport> {
  const tool = toolFor(tree, project, operation)
  // `--async` measures the asynchronous rotary driver and `--workers` its worker
  // pool; every other run stays on the synchronous entry, which is the app's
  // generation path.
  const asyncEntry = args.rotaryAsync ? tree.computeOperationToolpathAsync : undefined
  if (args.rotaryAsync && asyncEntry === undefined) {
    throw new ProbeError(
      `${tree.root} has no computeOperationToolpathAsync, so --async cannot measure it`,
    )
  }
  // One pool per generation: the factory is called once per operation, so a
  // generation's worker setup is inside its own measured time.
  const pools: RotaryAnglePool[] = []
  const source = args.workers === null ? null : createNodeRotaryAngleWorkerSource()
  const poolOptions = {
    ...(args.workers !== null ? { maxWorkers: args.workers } : {}),
    ...(args.poolBudgetMb !== null ? { maxBufferBytes: args.poolBudgetMb * 1048576 } : {}),
  }
  const details: RunDetail[] = []
  const run = async (): Promise<ToolpathResult> => {
    pools.length = 0
    const started = performance.now()
    let envelope: { result: ToolpathResult } | null
    if (asyncEntry === undefined) {
      envelope = tree.computeOperationToolpath(project, operation)
    } else if (source !== null) {
      const factory: RotaryBatchFactory = (prep) => {
        const pool = createRotaryAnglePool(prep, source, poolOptions)
        pools.push(pool)
        return pool.batches
      }
      envelope = await asyncEntry(project, operation, { rotaryRunBatch: factory })
    } else {
      envelope = await asyncEntry(project, operation)
    }
    details.push(runDetail(pools, performance.now() - started))
    for (const pool of pools) await pool.dispose()
    pools.length = 0
    if (!envelope) {
      throw new ProbeError(`the engine returned no toolpath for operation ${operation.id}`)
    }
    return envelope.result
  }

  // Cold: the first generation, whatever warm-up it carries. Nothing else is
  // timed — not the load, not the post — because the number #1115 promises is
  // a generation time.
  const coldStart = performance.now()
  let result = await run()
  const coldMs = roundMs(performance.now() - coldStart)

  const warmMs: number[] = []
  const digests = new Set<string>([digestMoves(result.moves)])
  for (let index = 0; index < WARM_RUNS; index += 1) {
    const start = performance.now()
    result = await run()
    warmMs.push(roundMs(performance.now() - start))
    digests.add(digestMoves(result.moves))
  }

  const machine = postMachine(tree, project)
  // The postprocessor reads the wall clock itself, so the probe cannot choose
  // the date; reading it either side of the call names the stamp the post may
  // have written even when the two are a midnight apart.
  const beforePost = generationDate()
  const posted = tree.runPostProcessor({
    project,
    operations: [{ operation, tool, toolpath: result }],
    definition: machine.definition,
    options: { emitToolChanges: true, emitCoolant: false, programName: project.meta.name },
  })
  const afterPost = generationDate()
  const generatedOn = beforePost === afterPost ? [beforePost] : [beforePost, afterPost]

  const setup = project.setups?.find((candidate) => candidate.id === operation.setupId) ?? null
  const axis = stockAxis(project)
  const setupAxis = setup && 'orientation' in setup ? setup.orientation.axis : null

  const movesByKind: Record<string, number> = {}
  let aMin = Number.POSITIVE_INFINITY
  let aMax = Number.NEGATIVE_INFINITY
  for (const move of result.moves) {
    movesByKind[move.kind] = (movesByKind[move.kind] ?? 0) + 1
    for (const point of [move.from, move.to]) {
      if (point.a === undefined) continue
      aMin = Math.min(aMin, point.a)
      aMax = Math.max(aMax, point.a)
    }
  }

  return {
    id: operation.id,
    identity: {
      id: operation.id,
      kind: operation.kind,
      axis: {
        stock: axis,
        setup: setupAxis ?? null,
        passDirection: operation.rotaryPassDirection ?? null,
      },
      tool,
      feeds: { feed: operation.feed, plungeFeed: operation.plungeFeed, rpm: operation.rpm },
      settings: {
        stepdown: operation.stepdown,
        stepover: operation.stepover,
        stockToLeaveRadial: operation.stockToLeaveRadial,
        stockToLeaveAxial: operation.stockToLeaveAxial,
        rotaryChuckSupport: operation.rotaryChuckSupport ?? null,
        rotaryTailSupport: operation.rotaryTailSupport ?? null,
        arcFittingEnabled: operation.arcFittingEnabled ?? null,
      },
      operation: structuredClone(operation),
      operationDigest: sha256(stableStringify(operation)),
      toolDigest: sha256(stableStringify(tool)),
    },
    runs: {
      coldMs,
      warmMs,
      medianMs: roundMs(median(warmMs)),
      minMs: Math.min(...warmMs),
      maxMs: Math.max(...warmMs),
      digestStable: digests.size === 1,
      details,
    },
    warnings: result.warnings.map((warning) => ({
      code: warning.code,
      ...(warning.params === undefined ? {} : { params: warning.params as Record<string, unknown> }),
    })),
    moves: { count: result.moves.length, digest: digestMoves(result.moves) },
    program: {
      machineId: machine.id,
      machineSource: machine.source,
      lines: posted.stats.lineCount,
      moves: posted.stats.moveCount,
      digest: digestProgram(posted.gcode, generatedOn, project.meta.name),
      warnings: posted.warnings.map((warning) => warning.code),
    },
    simulation: {
      stock: {
        shape: project.stock.shape ?? null,
        axis,
        thickness: project.stock.thickness,
      },
      toolRadius: tool.radius,
      movesByKind,
      aRangeDeg: aMin === Number.POSITIVE_INFINITY ? null : [aMin, aMax],
      bounds: result.bounds,
    },
  }
}

// ── baseline comparison ──────────────────────────────────────

function describeValue(value: unknown, limit = 60): string {
  const text = stableStringify(value)
  return text.length <= limit ? text : `${text.slice(0, limit - 1)}…`
}

/** Leaf paths whose values differ, with both readings, bounded for reading. */
function diffValues(
  baseline: unknown,
  candidate: unknown,
  prefix: string,
  out: Array<{ path: string; baseline: unknown; candidate: unknown }>,
  limit = 6,
): void {
  if (out.length >= limit) return
  const bothRecords = baseline !== null && candidate !== null
    && typeof baseline === 'object' && typeof candidate === 'object'
    && !Array.isArray(baseline) && !Array.isArray(candidate)
  if (bothRecords) {
    const left = baseline as Record<string, unknown>
    const right = candidate as Record<string, unknown>
    const keys = [...new Set([...Object.keys(left), ...Object.keys(right)])].sort()
    for (const key of keys) {
      diffValues(left[key], right[key], prefix ? `${prefix}.${key}` : key, out, limit)
      if (out.length >= limit) return
    }
    return
  }
  if (stableStringify(baseline) !== stableStringify(candidate)) {
    out.push({ path: prefix, baseline, candidate })
  }
}

/**
 * One mismatch naming the leaf fields whose values differ.
 *
 * `label` prefixes each path so a settings difference reads
 * `operation.stepover`; `noun` is how the report calls the thing that moved.
 */
function valueMismatch(
  kind: BaselineMismatchKind,
  operationId: string | null,
  label: string,
  noun: string,
  baseline: unknown,
  candidate: unknown,
): BaselineMismatch | null {
  const differences: Array<{ path: string; baseline: unknown; candidate: unknown }> = []
  diffValues(baseline, candidate, label, differences)
  const subject = operationId ?? 'the run'
  if (differences.length === 0) {
    // The caller's digest said "different" but the stored objects agree: say so
    // rather than pretending the values explain it.
    return {
      kind,
      operationId,
      detail: `${subject} ${noun} differ${label ? ` (${label})` : ''}`,
    }
  }
  const described = differences
    .map((entry) => `${entry.path} (baseline ${describeValue(entry.baseline)}, run ${describeValue(entry.candidate)})`)
    .join('; ')
  return { kind, operationId, detail: `${subject} ${noun} differ: ${described}` }
}

/**
 * A mismatch for fields compared by value rather than by a stored digest.
 *
 * Nothing is reported when the two readings agree: unlike the digest-driven
 * calls above, these are asked unconditionally, so "no difference" has to mean
 * "no mismatch".
 */
function identityMismatch(
  kind: BaselineMismatchKind,
  operationId: string | null,
  label: string,
  noun: string,
  baseline: unknown,
  candidate: unknown,
): BaselineMismatch | null {
  if (stableStringify(baseline) === stableStringify(candidate)) return null
  return valueMismatch(kind, operationId, label, noun, baseline, candidate)
}

/**
 * Everything that must be identical between a run and a stored baseline.
 *
 * Only identity and output: the timings are deliberately not compared here,
 * because a baseline is also the reference for a *later* slice that is meant
 * to be faster.
 */
export function compareReports(baseline: ProbeReport, candidate: ProbeReport): BaselineMismatch[] {
  const mismatches: BaselineMismatch[] = []

  if (baseline.fixture.sha256 !== candidate.fixture.sha256) {
    mismatches.push({
      kind: 'fixture',
      operationId: null,
      detail: `fixture hash differs: baseline ${baseline.fixture.sha256.slice(0, 12)} from ${baseline.fixture.path}, run ${candidate.fixture.sha256.slice(0, 12)} from ${candidate.fixture.path}`,
    })
  }

  // The stock's own axis lives outside the operation object the settings digest
  // covers, so a run cutting about a different axis would otherwise compare as
  // identical. It is identity, not settings, and it is compared explicitly.
  const stock = identityMismatch('stock', null, '', 'stock', baseline.stock, candidate.stock)
  if (stock) mismatches.push(stock)

  const baselineById = new Map(baseline.operations.map((operation) => [operation.id, operation]))
  const candidateById = new Map(candidate.operations.map((operation) => [operation.id, operation]))
  for (const id of candidateById.keys()) {
    if (!baselineById.has(id)) {
      mismatches.push({ kind: 'operation-set', operationId: id, detail: `operation ${id} is not in the baseline` })
    }
  }
  for (const id of baselineById.keys()) {
    if (!candidateById.has(id)) {
      mismatches.push({ kind: 'operation-set', operationId: id, detail: `operation ${id} is missing from the run` })
    }
  }

  for (const operation of candidate.operations) {
    const stored = baselineById.get(operation.id)
    if (!stored) continue

    // Which way the bar turns, and about which axis, is recorded on the
    // operation report but derived from the stock and the setup — neither of
    // which is inside `operation`, so the settings digest cannot see it.
    const axis = identityMismatch(
      'axis',
      operation.id,
      'axis',
      'rotation axis',
      stored.identity.axis,
      operation.identity.axis,
    )
    if (axis) mismatches.push(axis)

    if (stored.identity.operationDigest !== operation.identity.operationDigest) {
      const mismatch = valueMismatch(
        'settings',
        operation.id,
        'operation',
        'settings',
        stored.identity.operation,
        operation.identity.operation,
      )
      if (mismatch) mismatches.push(mismatch)
    }
    if (stored.identity.toolDigest !== operation.identity.toolDigest) {
      const mismatch = valueMismatch(
        'settings',
        operation.id,
        'tool',
        'settings',
        stored.identity.tool,
        operation.identity.tool,
      )
      if (mismatch) mismatches.push(mismatch)
    }
    if (stored.moves.digest !== operation.moves.digest) {
      mismatches.push({
        kind: 'moves',
        operationId: operation.id,
        detail: `${operation.id} moves differ: ${stored.moves.count} moves (baseline, ${stored.moves.digest.slice(0, 12)}) vs ${operation.moves.count} moves (run, ${operation.moves.digest.slice(0, 12)})`,
      })
    }
    if (stored.program.digest !== operation.program.digest) {
      mismatches.push({
        kind: 'program',
        operationId: operation.id,
        detail: `${operation.id} posted program differs: ${stored.program.lines} lines (baseline, ${stored.program.digest.slice(0, 12)}) vs ${operation.program.lines} lines (run, ${operation.program.digest.slice(0, 12)})`,
      })
    }
  }

  return mismatches
}

/** Read and lightly validate a stored result before comparing with it. */
export function readBaseline(path: string): ProbeReport {
  let text: string
  try {
    text = readFileSync(path, 'utf8')
  } catch (error) {
    throw new ProbeError(`cannot read baseline ${path}: ${error instanceof Error ? error.message : String(error)}`)
  }
  let parsed: unknown
  try {
    parsed = JSON.parse(text)
  } catch (error) {
    throw new ProbeError(`baseline ${path} is not JSON: ${error instanceof Error ? error.message : String(error)}`)
  }
  const report = parsed as Partial<ProbeReport>
  if (report.probe !== PROBE_NAME || !Array.isArray(report.operations)
    || (report.fixture as { sha256?: unknown } | undefined)?.sha256 === undefined) {
    throw new ProbeError(`${path} is not a ${PROBE_NAME} result`)
  }
  for (const operation of report.operations) {
    const stored = operation as Partial<OperationReport> | undefined
    const complete = stored?.identity !== undefined
      && typeof stored.identity.operationDigest === 'string'
      && typeof stored.identity.toolDigest === 'string'
      && typeof stored.moves?.digest === 'string'
      && typeof stored.program?.digest === 'string'
    if (!complete) {
      throw new ProbeError(`${path} is not a ${PROBE_NAME} result: an operation entry has no id, digests or output hash`)
    }
  }
  return report as ProbeReport
}

// ── the run ──────────────────────────────────────────────────

export async function measure(args: ProbeArgs): Promise<ProbeReport> {
  // Before the engine is loaded: a run whose result file would replace the
  // fixture must not measure anything at all.
  assertOutputIsNotFixture(args.out, args.project)

  // `--workers` samples with **this** checkout's kernel: the pool and the worker
  // adapter are imported from here, while `--root` only chooses where the
  // generation entry comes from. Measuring an older tree through this kernel
  // would compare two samplers and call it a speed-up. Checked before anything is
  // loaded, so a mistaken pairing costs no load.
  if (args.workers !== null && resolve(args.root) !== resolve(PROBE_ROOT)) {
    throw new ProbeError(
      `--workers samples with this checkout's kernel (${PROBE_ROOT}), but --root names ${args.root};`
      + ' measure one checkout at a time',
    )
  }

  const tree = await loadEngineTree(args.root)

  const bytes = readFileSync(args.project)
  const fixtureSha256 = sha256(bytes)
  let raw: unknown
  try {
    raw = JSON.parse(bytes.toString('utf8'))
  } catch (error) {
    throw new ProbeError(`${args.project} is not JSON: ${error instanceof Error ? error.message : String(error)}`)
  }
  // A fixture this checkout cannot load is a finding, not a crash: the point
  // of `--root` is to find out exactly that about another tree.
  let project: Project
  try {
    project = tree.normalizeProject(raw)
  } catch (error) {
    throw new ProbeError(
      `${args.project} does not load in ${tree.root}: ${error instanceof Error ? error.message : String(error)}`,
    )
  }
  const selected = selectOperations(project, args.operations)
  // A control changes the operations, never the project on disk: the copies go
  // to generation and posting, and `project.operations` is left as loaded.
  const measured = args.passDirection === null
    ? selected
    : withPassDirection(selected, args.passDirection)

  const operations: OperationReport[] = []
  for (const operation of measured) {
    operations.push(await operationReport(tree, project, operation, args))
  }

  return {
    probe: PROBE_NAME,
    version: PROBE_VERSION,
    generatedAt: new Date().toISOString(),
    engine: {
      entry: args.workers !== null
        ? `${ENGINE_ENTRY}Async + angle worker pool`
        : args.rotaryAsync
          ? `${ENGINE_ENTRY}Async`
          : ENGINE_ENTRY,
      root: tree.root,
      commit: tree.commit,
    },
    fixture: {
      path: args.project,
      bytes: bytes.length,
      // The bytes on disk, not a re-serialization: the hash has to name the
      // file that was measured even when this tree would normalize it
      // differently from the tree it was saved with.
      sha256: fixtureSha256,
      version: typeof (raw as { version?: unknown }).version === 'string'
        ? (raw as { version: string }).version
        : null,
      units: project.meta.units,
    },
    stock: {
      shape: project.stock.shape ?? null,
      axis: stockAxis(project),
      thickness: project.stock.thickness,
    },
    warmRuns: WARM_RUNS,
    operations,
    control: args.passDirection === null ? null : { passDirection: args.passDirection },
  }
}

function displayPath(path: string, base: string): string {
  const relativePath = relative(base, path)
  return relativePath === '' || relativePath.startsWith('..') ? path : relativePath
}

/** One line per run and operation: what the pool owned and what it did not. */
function formatPhases(report: ProbeReport): string {
  const lines: string[] = []
  for (const operation of report.operations) {
    operation.runs.details.forEach((detail, index) => {
      const label = index === 0 ? 'cold' : `warm ${index}`
      const pooled = detail.workers > 0
      const serialShare = Math.max(0, detail.totalMs - detail.installMs - detail.awaitMs)
      lines.push(
        `${operation.id} ${label}: ${detail.totalMs.toFixed(1)} ms total`
        + (pooled
          ? ` | ${detail.workers} workers, ${detail.mode}${detail.fallback === 'none' ? '' : ` (${detail.fallback} fallback)`}`
            + ` | install ${detail.installMs.toFixed(1)} ms | await ${detail.awaitMs.toFixed(1)} ms`
            + ` | coordinator remainder ${serialShare.toFixed(1)} ms`
            + ` | ${detail.batches} batches, ${detail.planRevisions} plan revisions`
            + ` | ${(detail.setupBytesPerWorker / 1048576).toFixed(1)} MB/worker`
          : ' | serial (in-process runner)')
        + ` | rss ${detail.rssMiB.toFixed(0)} MiB, peak ${detail.rssPeakMiB.toFixed(0)} MiB`,
      )
    })
  }
  return lines.join('\n')
}

function formatTable(report: ProbeReport, base: string): string {
  const rows = report.operations.map((operation) => ({
    id: operation.id,
    kind: operation.identity.kind,
    cold: operation.runs.coldMs.toFixed(1),
    warm: operation.runs.warmMs.map((value) => value.toFixed(1)).join('  '),
    median: operation.runs.medianMs.toFixed(1),
    moves: String(operation.moves.count),
    program: String(operation.program.lines),
  }))
  const header = {
    id: 'operation',
    kind: 'kind',
    cold: 'cold ms',
    warm: 'warm ms (x5)',
    median: 'median ms',
    moves: 'moves',
    program: 'program lines',
  }
  const width = (key: keyof typeof header): number =>
    Math.max(header[key].length, ...rows.map((row) => row[key].length))
  const line = (row: typeof header): string => [
    row.id.padEnd(width('id')),
    row.kind.padEnd(width('kind')),
    row.cold.padStart(width('cold')),
    row.warm.padEnd(width('warm')),
    row.median.padStart(width('median')),
    row.moves.padStart(width('moves')),
    row.program.padStart(width('program')),
  ].join('  ')
  const separator = Object.fromEntries(
    (Object.keys(header) as Array<keyof typeof header>).map((key) => [key, '-'.repeat(width(key))]),
  ) as typeof header

  return [
    `${PROBE_NAME}: fixture ${displayPath(report.fixture.path, base)} (${report.fixture.bytes} bytes, sha256 ${report.fixture.sha256.slice(0, 16)}…)`,
    `engine ${report.engine.root}${report.engine.commit ? ` @ ${report.engine.commit}` : ''}, entry ${report.engine.entry}`,
    `stock ${report.stock.shape ?? 'block'}${report.stock.axis ? ` along ${report.stock.axis}` : ''}, ${report.stock.thickness} ${report.fixture.units}`,
    ...(report.control
      ? [`control: pass direction ${report.control.passDirection}, built in memory (fixture unchanged)`]
      : []),
    `runs: 1 cold + ${report.warmRuns} warm forced regenerations per operation`,
    '',
    line(header),
    line(separator),
    ...rows.map(line),
  ].join('\n')
}

const USAGE = `Usage: npx tsx scripts/rotary-generation-probe.ts --project <file.camj> --operation <id> [--operation <id>…]
       [--pass-direction <around|along>] [--async] [--workers <n>] [--pool-budget-mb <n>]
       [--out <json>] [--root <checkout>] [--baseline <json>]

  --project   the .camj to read (never written)
  --operation operation id to measure; repeat for more than one
  --pass-direction
              build an along/around control in memory: the selected operations
              are copied with that pass direction after load, and the fixture
              stays untouched (so the report's fixture hash is the original's)
  --async     measure the asynchronous rotary driver (computeOperationToolpathAsync)
              through its in-process serial batch runner; refused when the
              measured checkout has no such entry
  --workers   measure the same driver through the angle worker pool with at most
              <n> Node worker_threads workers (also capped by the pool's own
              eight-worker ceiling, cores - 2, and its buffer budget); the report
              records the workers actually used, the install/await split and the
              process peak RSS, and it refuses --root with another checkout
  --pool-budget-mb
              raise the pool's typed-buffer budget from its 512 MiB default, for
              a run that needs to see the uncapped worker ceiling
  --out       result JSON (default: work/rotary-generation-probe.json in this checkout);
              rejects the fixture's own path, including a symlink or hardlink to it
  --root      checkout whose engine is measured (default: this checkout)
  --baseline  stored result to compare with; exits 1 on any identity or output difference`

async function main(argv: readonly string[]): Promise<void> {
  const probeRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
  const defaults: ProbeDefaults = {
    out: join(probeRoot, 'work', `${PROBE_NAME}.json`),
    root: probeRoot,
  }
  if (argv.includes('--help') || argv.length === 0) {
    console.log(USAGE)
    return
  }
  const args = parseProbeArgs(argv, defaults)
  const report = await measure(args)

  if (args.baseline !== null) {
    const baseline = readBaseline(args.baseline)
    const mismatches = compareReports(baseline, report)
    report.baseline = {
      path: args.baseline,
      status: mismatches.length === 0 ? 'match' : 'mismatch',
      mismatches,
    }
  }

  mkdirSync(dirname(args.out), { recursive: true })
  writeFileSync(args.out, `${JSON.stringify(report, null, 2)}\n`)

  console.log(formatTable(report, probeRoot))
  if (report.operations.some((operation) => operation.runs.details.length > 0)) {
    console.log('')
    console.log(formatPhases(report))
  }
  for (const operation of report.operations) {
    if (!operation.runs.digestStable) {
      console.error(
        `${PROBE_NAME}: WARNING operation ${operation.id} produced different moves between runs; a timing baseline over non-deterministic output is meaningless`,
      )
    }
    if (operation.warnings.length > 0) {
      console.log(
        `${operation.id} generation warnings: ${operation.warnings.map((warning) => warning.code).join(', ')}`,
      )
    }
    if (operation.program.warnings.length > 0) {
      console.log(
        `${operation.id} post warnings: ${operation.program.warnings.join(', ')}`,
      )
    }
  }
  console.log(`result ${displayPath(args.out, probeRoot)}`)

  const baselinePath = report.baseline?.path
  if (baselinePath !== undefined && report.baseline) {
    if (report.baseline.status === 'match') {
      console.log(`baseline ${displayPath(baselinePath, probeRoot)}: match`)
    } else {
      console.error(`baseline ${displayPath(baselinePath, probeRoot)}: MISMATCH`)
      for (const mismatch of report.baseline.mismatches) {
        console.error(`  ${mismatch.detail}`)
      }
      process.exitCode = 1
    }
  }
}

const invokedDirectly = process.argv[1] !== undefined
  && resolve(process.argv[1]) === fileURLToPath(import.meta.url)

if (invokedDirectly) {
  main(process.argv.slice(2)).catch((error: unknown) => {
    if (error instanceof ProbeError) {
      console.error(`${PROBE_NAME}: ${error.message}`)
    } else {
      console.error(error)
    }
    process.exitCode = 1
  })
}

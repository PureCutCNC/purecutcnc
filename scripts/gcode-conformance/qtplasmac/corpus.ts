/**
 * Plasma corpus for the QtPlasmaC simulator check (issue #954).
 *
 * Four groups, all run the same way:
 *
 * - `REFERENCE_CASES` — hand-written programs in `fixtures/`, taken from the
 *   QtPlasmaC manual. They must pass. They prove the harness accepts a correct
 *   program, and they are the shape the plasma post output (#959) aims at.
 * - `NEGATIVE_CASES` — `fixtures/negative/`, each a reference program with one
 *   defect. They must be rejected, each for exactly its own rules. This is the
 *   mutation check: if one of these passes, or trips fewer rules than it
 *   should, the harness is not checking that rule.
 * - `EXPORTED_CASES` — programs generated by the plasma exporter (#959), each
 *   the twin of a reference case. They must pass.
 * - `HARNESS_CASES` — the harness checking itself in the real simulator.
 */

import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Expectation } from './verdict'
import { exportPlasma, PLASMA_EXPORT_SCENARIOS } from '../../../src/test/plasmaExportFixtures'

/** Which simulator configuration runs the case — the machine's units, not the program's. */
export type SimMachine = 'metric' | 'imperial'

export interface PlasmaCase {
  /** File-safe identifier, unique across the corpus. */
  name: string
  /** Why this case exists — printed alongside the result. */
  covers: string
  machine: SimMachine
  /** The program text. A function so an exported case is generated on demand. */
  program: () => string
  expect: Expectation
  /**
   * Harness self-check only: have the driver sabotage this program's first
   * Cycle Start, and require that it took exactly `startAttempts` presses.
   */
  fault?: 'refused-start'
  startAttempts?: number
  /**
   * The program must make QtPlasmaC apply its automatic small-hole feed
   * reduction at run time. Set on the exported small-hole case; the header
   * alone (`#<holes> = 1`) is not evidence that the reduction happened.
   */
  expectHoleReduction?: boolean
}

const FIXTURE_DIR = join(import.meta.dirname, 'fixtures')

function fixture(relativePath: string): () => string {
  return () => readFileSync(join(FIXTURE_DIR, relativePath), 'utf8')
}


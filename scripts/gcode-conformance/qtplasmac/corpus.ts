/**
 * Checks of the harness itself, run in the real simulator alongside the corpus.
 *
 * `refused-cycle-start` is the regression for a start that never happened
 * going unnoticed (#954). The driver puts LinuxCNC back in manual mode just
 * before the first Cycle Start, the way the QtPlasmaC GUI can, and changes the
 * material so the trace shows a feed change with nothing running. The driver
 * must notice the refusal and press again: two presses, and then a correct
 * program must still pass. One press means the refusal was mistaken for a
 * start.
 */
export const HARNESS_CASES: PlasmaCase[] = [
  {
    name: 'refused-cycle-start',
    covers: 'harness self-check: a refused Cycle Start is noticed and repeated, not taken for a run',
    machine: 'metric',
    program: fixture('single-outline.ngc'),
    expect: 'pass',
    fault: 'refused-start',
    startAttempts: 2,
  },
]


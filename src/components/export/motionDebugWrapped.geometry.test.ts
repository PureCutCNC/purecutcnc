/**
 * The 3D wrapped view against real geometry (issue #1179, correction round 5).
 *
 * Frank's app check reported the Hex's six flats drawn curved in the view while
 * the Simulation tab showed them flat. This suite settles which one is wrong on
 * geometry the test builds itself — a 38.1 mm across-flats Hex on a Ø50.8 mm
 * round bar, the same proportions as his bolt — generated by the app's own
 * planners and exported by the real post-processor, then read back through the
 * dialog's own conversion (`parseExportedMotion` → `buildWrappedMotion`).
 *
 * It pins three things:
 *
 * 1. **The view is faithful.** Every drawn point of the exported layer sits on
 *    the radius the program's own machine word asks for — `radius = stock
 *    radius + Z`, with the machine's Z zero on top of the bar (the project
 *    origin's z is the stock thickness, so `origin.z - barPivotZ` is exactly the
 *    stock radius) — at that point's own A and X. A wrong Z/radius map, a
 *    reversed A frame, or an across/angle mix-up all break it. The machine→
 *    project map, the wrap and the angle are then checked again on the drawn
 *    point itself (its stock-space angle must be the commanded A).
 * 2. **Generated and Exported coincide** where the optimizer left the program
 *    alone: the two layers draw the same pieces, point for point, within the
 *    program's three-decimal rounding.
 * 3. **A flat face draws flat** where the program is flat. The drawn point is
 *    the *tool tip*; on a tilted flat facet a ball nose's tip rides above the
 *    facet by `(apothem + r)/cos θ - r` because the ball touches the plane at
 *    its side, not at its tip (θ is the angle from the facet normal). So the
 *    face is measured where the material is: the ball's closest approach to the
 *    facet plane, `(tip - ballTip(θ))·cos θ`. Along passes (this finish's
 *    default) reach the plane within the finish's own scallop; Around passes do
 *    not — the Around sampler's conservative angular cell lifts the tip by one
 *    angle step, leaving a wedge that grows to the facet edge. That residue is
 *    the *program's*, not the view's (item 4 of the review: it belongs to
 *    #1177), so the Around case only asserts the view adds nothing and that no
 *    point gouges the face; its measured wedge is printed.
 *
 * Run with: npx tsx src/components/export/motionDebugWrapped.geometry.test.ts
 */


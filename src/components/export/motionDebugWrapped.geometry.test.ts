/** The bar and the Hex, at the proportions of Frank's bolt-test-02. */
const BAR_DIAMETER = 50.8
const BAR_LENGTH = 101.6
const HEAD_START = 19.05
const HEAD_LENGTH = 12.7
const ACROSS_FLATS = 38.1
const BALL_DIAMETER = 3.175
/** Half the across-flats: the distance of every facet plane from the axis. */
const APOTHEM = ACROSS_FLATS / 2
/** Ball-nose radius: the tip is the ball's lowest point, so the plane is `r` away. */
const BALL_RADIUS = BALL_DIAMETER / 2
/** A band inside the head, so neither end face nor a retained stub is read. */
const BAND_START = 24
const BAND_END = 27
/** How far from a facet normal the sample may sit before the corner is read. */
const FACET_LIMIT_DEGREES = 24
/** The finish's own scallop plus the sampler's 0.005 mm angle tolerance. */
const FLAT_TOLERANCE_MM = 0.01

/** The planner's selection argument, unused by the canned-solid path. */
const EMPTY_SELECTION = {
  mode: 'feature', selectedFeatureId: null, selectedFeatureIds: [], selectedTabIds: [],
  selectedClampIds: [], selectedNode: null, hoveredFeatureId: null, sketchEditTool: null,
  activeControl: null, groupFolderId: null,
} as unknown as SelectionState

function machineDefinition(): MachineDefinition {
  const found = BUNDLED_DEFINITIONS.find((definition) => definition.id === 'grbl-rotary-a')
  assert.ok(found, 'the bundled A-axis rotary machine exists')
  return structuredClone(found)
}

/** A project whose only work is a Hex head on a round bar, in the Around setup. */
function hexProject(): { project: Project; hexId: string } {
  const base = newProject('hex face check', 'mm')
  base.meta.projectType = 'rotary'
  base.meta.maxTravelZ = BAR_DIAMETER
  base.stock = roundStock(BAR_DIAMETER, BAR_LENGTH, 'x')
  // Z zero on top of the bar: the origin's z is the stock thickness, which is
  // how the exported program's Z words read (`radius = R + Z`).
  base.origin = { ...base.origin, x: 0, y: BAR_DIAMETER / 2, z: BAR_DIAMETER }
  base.tools = [{
    ...defaultTool('mm', 1), id: 'ball-nose', name: '1/8 ball', type: 'ball_endmill',
    diameter: BALL_DIAMETER, defaultStepover: 0.16,
  }]
  base.setups.push({
    ...base.setups[0], id: 'around', name: 'Around', kind: 'around',
    orientation: { axis: 'x', angleDeg: 0 },
  })
  base.activeSetupId = 'around'
  const hex = planRotarySolid(base, EMPTY_SELECTION, {
    kind: 'polygon', start: HEAD_START, length: HEAD_LENGTH, sides: 6,
    acrossFlats: ACROSS_FLATS, rotationDeg: 0,
  })
  if (!hex.ok) throw new Error(`the Hex must plan: ${hex.reason}`)
  return { project: hex.project, hexId: hex.created.featureId }
}

interface Scenario {
  stock: BarStock
  radius: number
  centre: number
  pivot: number
  parsed: ParsedGcodeMotion
  wrapped: WrappedMotionModel
  result: ToolpathResult
}

/**
 * Generate, export and read back one Hex finish. `around` is the pass direction
 * Frank's bolt uses; `along` is the finish's default, and the control: its
 * facets are flat.
 */
function hexFinish(direction: 'along' | 'around'): Scenario {
  const { project, hexId } = hexProject()
  const operation = {
    ...defaultOperationForTarget(
      project, 'rotary_finish', 'finish', { source: 'features', featureIds: [hexId] }, 1,
    ),
    setupId: 'around',
    toolRef: 'ball-nose',
    stepover: 0.16,
    stockToLeaveRadial: 0,
    rotaryPassDirection: direction,
  }
  const tool = project.tools.find((candidate) => candidate.id === operation.toolRef)
  assert.ok(tool, 'the finish has its tool')
  const envelope = computeOperationToolpath(project, operation)
  assert.ok(envelope, 'the Hex finish generates')
  const result = envelope.result
  assert.ok(result.moves.some((move) => move.from.a !== undefined), 'the finish commands rotary angles')

  const definition = pinRotaryAxis(machineDefinition(), project.stock)
  const program = runPostProcessor({
    project,
    operations: [{ operation, tool: normalizeToolForProject(tool, project), toolpath: result }],
    definition,
    options: { emitToolChanges: false, emitCoolant: false, programName: 'hex-finish', captureMotionTrace: true },
  })
  const parsed = parseExportedMotion(program.gcode, definition)
  assert.notEqual(parsed.status, 'failed', 'the exported program parses')
  const stock = project.stock
  assert.ok(isBarStock(stock), 'the project has a bar')
  const wrapped = buildWrappedMotion({
    parsed,
    origin: project.origin,
    definition,
    stock,
    trace: { operationId: operation.id, raw: result, optimized: result },
  })
  assert.ok(wrapped, 'a turning program has a wrapped model')
  return {
    stock,
    radius: barInscribedRadius(stock),
    centre: barCentre(stock),
    pivot: barPivotZ(stock),
    parsed,
    wrapped,
    result,
  }
}

/** The drawn endpoints of one layer that are feeds, in program order. */
function drawnFeeds(scenario: Scenario, layer: 'optimized' | 'exported'): Array<{
  from: { x: number; y: number; z: number }
  to: { x: number; y: number; z: number }
  aFrom?: number
  aTo?: number
}> {
  return scenario.wrapped.layers[layer].filter((piece) => !piece.rapid)
}

/** One drawn point's cross-section radius about the bar axis. */
function drawnRadius(scenario: Scenario, point: { y: number; z: number }): number {
  return Math.hypot(point.y - scenario.centre, point.z - scenario.pivot)
}

/** One drawn point's stock-space angle, in degrees, from the bar's top. */
function drawnAngle(scenario: Scenario, point: { y: number; z: number }): number {
  return (Math.atan2(point.y - scenario.centre, point.z - scenario.pivot) * 180) / Math.PI
}

/** A signed difference wrapped into (-180, 180]. */
function angleDelta(a: number, b: number): number {
  let delta = a - b
  while (delta > 180) delta -= 360
  while (delta <= -180) delta += 360
  return delta
}

/**
 * 1. Every drawn exported point lies on the radius the program's own machine
 * word asks for, at its own A and X.
 *
 * The program's points are indexed by (X, A) rounded to the machine's three
 * decimals — the same numbers the wrap was handed — so a placeholder rapid and
 * a cut at the same X/A cannot be confused: the nearest radius wins, which is
 * the only thing a faithful view can produce.
 */
function testViewIsFaithful(scenario: Scenario, label: string): void {
  console.log(`Testing the 3D view draws the program's own radius (${label})...`)
  const programRadii = new Map<string, number[]>()
  for (const move of scenario.parsed.moves) {
    for (const point of [move.from, move.to]) {
      if (point.a === undefined) continue
      const key = `${Math.round(point.x * 1e3)}|${Math.round(point.a * 1e3)}`
      // Z zero is on top of the bar, so the program's Z is a depth below it:
      // radius = stock radius + Z.
      const radius = scenario.radius + point.z
      const list = programRadii.get(key)
      if (list) list.push(radius)
      else programRadii.set(key, [radius])
    }
  }

  let checked = 0
  let unmatched = 0
  let maxRadiusError = 0
  let maxAngleError = 0
  let maxXError = 0
  for (const piece of drawnFeeds(scenario, 'exported')) {
    for (const [point, angle] of [[piece.from, piece.aFrom], [piece.to, piece.aTo]] as const) {
      if (angle === undefined) continue
      const candidates = programRadii.get(`${Math.round(point.x * 1e3)}|${Math.round(angle * 1e3)}`)
      if (candidates === undefined) {
        unmatched += 1
        continue
      }
      const radius = drawnRadius(scenario, point)
      const nearest = candidates.reduce(
        (best, candidate) => Math.abs(candidate - radius) < Math.abs(best - radius) ? candidate : best,
        candidates[0],
      )
      maxRadiusError = Math.max(maxRadiusError, Math.abs(nearest - radius))
      maxAngleError = Math.max(maxAngleError, Math.abs(angleDelta(drawnAngle(scenario, point), angle)))
      maxXError = Math.max(maxXError, Math.abs(point.x - Number(`${Math.round(point.x * 1e3)}`) / 1e3))
      checked += 1
    }
  }

  assert.ok(checked > 1000, `most of the program was measured (${checked} points)`)
  assert.equal(unmatched, 0, 'every drawn point came from a program point at its own X and A')
  assert.ok(maxRadiusError <= FLAT_TOLERANCE_MM,
    `drawn radius is the program's radius + Z (max ${maxRadiusError.toExponential(2)} mm off)`)
  assert.ok(maxAngleError <= 1e-6,
    `drawn angle is the commanded A (max ${maxAngleError.toExponential(2)}° off)`)
  assert.ok(maxXError <= 1e-3, `drawn along position is the program's X (max ${maxXError.toExponential(2)} mm off)`)
  console.log(`   ${checked} points, max radius error ${maxRadiusError.toExponential(2)} mm, `
    + `max angle error ${maxAngleError.toExponential(2)}°`)
}

/**
 * 2. The two drawn layers coincide where the program is unchanged: same pieces,
 * same endpoints, to within the program's three-decimal rounding.
 */
function testLayersCoincide(scenario: Scenario, label: string): void {
  console.log(`Testing Generated and Exported coincide (${label})...`)
  const optimized = drawnFeeds(scenario, 'optimized')
  const exported = drawnFeeds(scenario, 'exported')
  assert.equal(exported.length, optimized.length, 'both layers draw the same number of feed pieces')
  let maxDelta = 0
  for (let index = 0; index < optimized.length; index++) {
    for (const [a, b] of [[optimized[index].from, exported[index].from], [optimized[index].to, exported[index].to]] as const) {
      maxDelta = Math.max(maxDelta, Math.abs(a.x - b.x), Math.abs(a.y - b.y), Math.abs(a.z - b.z))
    }
  }
  assert.ok(maxDelta <= FLAT_TOLERANCE_MM,
    `the layers coincide (max ${maxDelta.toExponential(2)} mm apart)`)
  console.log(`   ${optimized.length} feed pieces, max endpoint delta ${maxDelta.toExponential(2)} mm`)
}

interface FacetSample {
  tilt: number
  tip: number
  ballTip: number
  /** How far the ball's surface stays outside the facet plane, mm. */
  leftover: number
}

/**
 * The drawn points on one Hex facet, in a mid-head band, measured against the
 * facet plane. `leftover` is the ball's closest approach distance outside the
 * plane: zero means the face is reached, positive means material is left.
 */
function facetSamples(scenario: Scenario): FacetSample[] {
  const samples: FacetSample[] = []
  for (const piece of drawnFeeds(scenario, 'exported')) {
    if (piece.aFrom === undefined || piece.aTo === undefined) continue
    // #1177: each drawn piece is sampled along its length (every 0.5 mm or
    // less), not only at its two ends. The ball finish reads the exact sphere
    // drop, so an Along pass over a flat facet holds one radius and merges into
    // a single piece the length of the Hex, with no endpoint inside the band.
    // A piece is a straight line in the view, so a point along it is drawn
    // exactly where the sample puts it.
    const length = Math.hypot(piece.to.x - piece.from.x, piece.to.y - piece.from.y, piece.to.z - piece.from.z)
    const steps = Math.max(1, Math.ceil(length / 0.5))
    for (let step = 0; step <= steps; step++) {
      const f = step / steps
      const point = {
        x: piece.from.x + (piece.to.x - piece.from.x) * f,
        y: piece.from.y + (piece.to.y - piece.from.y) * f,
        z: piece.from.z + (piece.to.z - piece.from.z) * f,
      }
      const angle = piece.aFrom + (piece.aTo - piece.aFrom) * f
      if (point.x < BAND_START || point.x > BAND_END) continue
      // The Hex is planned with a facet normal up, so the tilt away from the
      // nearest facet normal is the commanded angle folded into one facet.
      let tilt = ((angle % 60) + 60) % 60
      if (tilt > 30) tilt -= 60
      if (Math.abs(tilt) > FACET_LIMIT_DEGREES) continue
      const cosine = Math.cos((tilt * Math.PI) / 180)
      // The tip radius a ball of this radius needs to touch the plane there.
      const ballTip = (APOTHEM + BALL_RADIUS) / cosine - BALL_RADIUS
      const tip = drawnRadius(scenario, point)
      samples.push({ tilt, tip, ballTip, leftover: (tip - ballTip) * cosine })
    }
  }
  assert.ok(samples.length > 500, `the facet band holds enough points (${samples.length})`)
  return samples
}

/**
 * 3. A flat face draws flat. On the Along finish the ball reaches the facet
 * plane everywhere, within the finish's scallop and the sampler's angle
 * tolerance; every drawn point must reproduce that. The drawn tip itself rides
 * above the plane by the ball's own geometry — that is the machine's position,
 * not an error — so the check is on the ball's closest approach.
 */
function testFlatFaceDrawsFlat(scenario: Scenario): void {
  console.log('Testing a flat Hex face draws flat (Along finish)...')
  const samples = facetSamples(scenario)
  let worst = 0
  for (const sample of samples) worst = Math.max(worst, Math.abs(sample.leftover))
  assert.ok(worst <= FLAT_TOLERANCE_MM,
    `the facet plane is reached everywhere (worst ${worst.toFixed(4)} mm off)`)
  console.log(`   ${samples.length} points, worst ${worst.toFixed(4)} mm off the facet plane`)
}

/**
 * The Around finish, the one Frank's bolt exports. Before #1177 the facet was
 * *not* flat in the program (the Around sampler's conservative cell left a wedge
 * growing to the facet edge); the ball now reads the exact sphere drop and the
 * printed wedge is about 0.001 mm. This still pins only the view's part of it —
 * nothing gouges the face and the facet's own middle is on the plane.
 */
function testAroundFinishLiftsTheTip(scenario: Scenario): void {
  console.log('Measuring the Around finish\'s facet wedge (the program, not the view)...')
  const samples = facetSamples(scenario)
  let worstGouge = 0
  let worstLeftover = 0
  let middle = 0
  for (const sample of samples) {
    worstGouge = Math.min(worstGouge, sample.leftover)
    worstLeftover = Math.max(worstLeftover, sample.leftover)
    if (Math.abs(sample.tilt) <= 1) middle = Math.max(middle, Math.abs(sample.leftover))
  }
  // The face's own middle is on the plane; the tip only ever rises from it, so
  // the view cannot be inventing a bow (a gouge or a sign flip would show here).
  assert.ok(middle <= FLAT_TOLERANCE_MM,
    `the facet's middle is drawn on the plane (${middle.toFixed(4)} mm off)`)
  assert.ok(worstGouge >= -FLAT_TOLERANCE_MM,
    `no drawn point cuts into the facet (worst ${worstGouge.toFixed(4)} mm)`)
  // The wedge is the sampler's conservative angular cell: one angle step of the
  // surface slope, so it grows with the tilt away from the facet normal.
  let previous = -Infinity
  const table: string[] = []
  for (const tilt of [0, 4, 8, 12, 16, 20, 24]) {
    const near = samples.filter((sample) => Math.abs(sample.tilt - tilt) <= 0.5)
    if (near.length === 0) continue
    const average = near.reduce((sum, sample) => sum + sample.leftover, 0) / near.length
    assert.ok(average >= previous - 0.01, `the wedge grows with the tilt (A±${tilt}°)`)
    previous = average
    table.push(`A${tilt}: tip ${near[0].tip.toFixed(3)}, touching ${near[0].ballTip.toFixed(3)}, `
      + `left ${average.toFixed(3)} mm`)
  }
  console.log(`   the Around finish leaves up to ${worstLeftover.toFixed(3)} mm on the facet:`)
  for (const line of table) console.log(`     ${line}`)
}

/** The exported program's A span covers the turn it makes. */
function testAngleRange(scenario: Scenario, label: string): void {
  assert.ok(scenario.wrapped.aRange !== null, `${label}: the program carries an angle`)
  const range = scenario.wrapped.aRange
  assert.ok(range.max - range.min >= 360, `${label}: the A span covers the turn (${range.min}..${range.max})`)
}

for (const direction of ['along', 'around'] as const) {
  const scenario = hexFinish(direction)
  const label = direction === 'along' ? 'Along finish' : 'Around finish'
  console.log(`\n${label}: ${scenario.result.moves.length} moves, `
    + `${scenario.parsed.moves.length} program moves, stock radius ${scenario.radius} mm`)
  testViewIsFaithful(scenario, label)
  testLayersCoincide(scenario, label)
  testAngleRange(scenario, label)
  if (direction === 'along') testFlatFaceDrawsFlat(scenario)
  else testAroundFinishLiftsTheTip(scenario)
}


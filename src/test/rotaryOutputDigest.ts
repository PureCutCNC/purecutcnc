import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { BUNDLED_DEFINITIONS } from '../engine/gcode/definitions'
import { runPostProcessor } from '../engine/gcode/postprocessor'
import { validateMachineDefinition } from '../engine/gcode/types'
import { normalizeToolForProject } from '../engine/toolpaths/geometry'
import type { ToolpathResult } from '../engine/toolpaths/types'
import type { Operation, Project } from '../types/project'

/** Fingerprint the ordered toolpath and posted bytes, excluding the generated date. */
export function rotaryOutputDigest(project: Project, operation: Operation, result: ToolpathResult): string {
  const definition = BUNDLED_DEFINITIONS.find((candidate) => candidate.id === 'grbl')
  const stock = project.stock
  assert.ok(definition && (stock.shape === 'round' || stock.shape === 'square'))
  const rotary = { about: stock.axis, drive: 'own', reversed: false, inverseTimeFeed: { on: 'G93', off: 'G94' } }
  const toolRecord = project.tools.find((candidate) => candidate.id === operation.toolRef)
  assert.ok(toolRecord, 'the posted operation has a tool')
  const gcode = runPostProcessor({
    project,
    operations: [{ operation, tool: normalizeToolForProject(toolRecord, project), toolpath: result }],
    definition: validateMachineDefinition({ ...definition, rotary }),
    options: { emitToolChanges: true, emitCoolant: false, programName: project.meta.name },
  }).gcode.replace(/Generated by PureCutCNC on \d{4}-\d{2}-\d{2}/g, 'Generated by PureCutCNC on <date>')
  assert.match(gcode, /\bG93\b/, 'the post emits rotary motion')
  const { moves, warnings, bounds } = result
  const hash = createHash('sha256')
  hash.update(JSON.stringify({ moves, warnings, bounds }, (_key: string, value: unknown) => {
    if (typeof value !== 'number') return value
    if (Object.is(value, -0)) return '-0'
    return Number.isFinite(value) ? value : String(value)
  }))
  hash.update('\0')
  hash.update(gcode)
  return hash.digest('hex')
}

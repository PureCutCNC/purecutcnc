function assert(condition: unknown, message: string): asserts condition {
  if (!condition) throw new Error(`Assertion failed: ${message}`)
}

// ── Fixture: Top pocket, Bottom pocket, flipped about X ───────

const STOCK = { x: 10, y: 5, w: 100, h: 80, t: 20 }
const DEPTH = 6
const TOP_RECT = { x: 20, y: 15, w: 24, h: 14 }
const BOTTOM_RECT = { x: 72, y: 32, w: 20, h: 16 }

function pocket(id: string, rect: typeof TOP_RECT, zTop: number, zBottom: number, face: SetupFace): SketchFeature {
  return {
    id, name: id, kind: 'rect', folderId: null,
    sketch: {
      profile: rectProfile(rect.x, rect.y, rect.w, rect.h),
      origin: { x: 0, y: 0 }, orientationAngle: 0, dimensions: [], constraints: [],
    },
    operation: 'subtract', z_top: zTop, z_bottom: zBottom, authoringFace: face, visible: true, locked: false,
  }
}

function operation(id: string, featureId: string, setupId: string): Operation {
  return {
    id, name: id, kind: 'pocket', pass: 'rough', enabled: true, showToolpath: true, debugToolpath: false,
    target: { source: 'features', featureIds: [featureId] }, toolRef: 't1', setupId,
    stepdown: DEPTH, stepover: 0.4, feed: 600, plungeFeed: 180, rpm: 18000,
    pocketPattern: 'offset', pocketAngle: 0, stockToLeaveRadial: 0, stockToLeaveAxial: 0,
    finishWalls: true, finishFloor: true, carveDepth: 2, maxCarveDepth: 2,
    cutDirection: 'conventional', machiningOrder: 'level_first',
  }
}

function makeProject(): Project {
  const base = newProject('sim-model', 'mm')
  base.meta = { ...base.meta, operationClearanceZ: 8 }
  base.stock = { ...base.stock, profile: rectProfile(STOCK.x, STOCK.y, STOCK.w, STOCK.h), thickness: STOCK.t }
  base.origin = { name: 'Origin', x: STOCK.x, y: STOCK.y + STOCK.h, z: STOCK.t, visible: true }
  base.tools = [{ ...defaultTool('mm', 1), id: 't1', name: 'Flat', diameter: 6, maxCutDepth: 40 }]
  const clamp: Clamp = { id: 'clamp-1', name: 'Clamp', type: 'step_clamp', x: 14, y: 8, w: 6, h: 4, height: 10, visible: true }
  base.clamps = [clamp]
  const withFeatures = projectWithFeatures(base, [
    pocket('top-pocket', TOP_RECT, STOCK.t, STOCK.t - DEPTH, 'top'),
    pocket('bottom-pocket', BOTTOM_RECT, DEPTH, 0, 'bottom'),
  ])
  const topId = withFeatures.activeSetupId
  const synced = syncProjectSetups({
    ...withFeatures,
    operations: [
      operation('opTop', 'top-pocket', topId),
      // A second Bottom-face operation listed after Top, so a playback that
      // replayed every prior operation would carry Top's cut into Bottom.
      operation('opBottom', 'bottom-pocket', topId),
    ],
  })
  return withBottomSetup(synced, { axis: 'x', operationIds: ['opBottom'] })
}

function generate(project: Project, id: string): ToolpathResult {
  const op = project.operations.find((entry) => entry.id === id)
  assert(op, `fixture: ${id} exists`)
  const envelope = computeOperationToolpath(project, op)
  assert(envelope, `fixture: ${id} is generated`)
  return envelope.result
}

/**
 * The deferred entry point the hook awaits, with the same setup scoping the
 * hook builds. The hook's tab-switch render is asserted separately to be a
 * loading state, so the frame checks read the build that follows it.
 */
function builtResult(project: Project): SimulationResultInput['setupInput'] {
  const paths = new Map<string, ToolpathResult>(project.operations.map((entry) => [entry.id, generate(project, entry.id)]))
  return buildSimulationSetupInput(project, activeSetup(project), paths)
}

async function selectedResult(project: Project, selectedId: string) {
  const selected = project.operations.find((entry) => entry.id === selectedId)
  assert(selected, `fixture: ${selectedId} exists`)
  const setupInput = builtResult(project)
  const result = await computeSimulationResultAsync({
    setupInput,
    project,
    simulationMode: 'selected',
    simulationDetailCells: 240,
    selectedInSetup: selected,
    paths: new Map(),
  })
  assert(result, 'the deferred simulation build completes')
  return result
}

function topZAt(grid: SimulationGrid, x: number, y: number): number {
  const col = Math.min(grid.cols - 1, Math.max(0, Math.floor((x - grid.originX) / grid.cellSize)))
  const row = Math.min(grid.rows - 1, Math.max(0, Math.floor((y - grid.originY) / grid.cellSize)))
  return grid.topZ[row * grid.cols + col]
}

/** Mirror about the stock's X axis line — literal arithmetic, not the engine's. */
function flipY(point: { x: number; y: number }): { x: number; y: number } {
  return { x: point.x, y: 2 * (STOCK.y + STOCK.h / 2) - point.y }
}

const centre = (rect: typeof TOP_RECT) => ({ x: rect.x + rect.w / 2, y: rect.y + rect.h / 2 })

type Args = Parameters<typeof useSimulationModel>[0]
type Result = ReturnType<typeof useSimulationModel>

function render(args: Args): Result {
  let captured: Result | null = null
  function Capture() {
    // eslint-disable-next-line react-hooks/globals
    captured = useSimulationModel(args)
    return null
  }
  renderToStaticMarkup(createElement(Capture))
  assert(captured, 'useSimulationModel rendered')
  return captured
}

function selectedArgs(project: Project, id: string, toolpath: ToolpathResult): Args {
  const selectedOperation = project.operations.find((entry) => entry.id === id) ?? null
  return {
    project, centerTab: 'simulation', simulationMode: 'selected', simulationDetailCells: 240,
    selectedOperation, selectedToolpath: toolpath, requestToolpath: () => Promise.resolve(null),
  }
}

/** The store as `revealOperationFace` and the face switch read it. */
function resetStore(project: Project): void {
  useProjectStore.setState({ project })
}

const onTop = (project: Project): Project => ({ ...project, activeSetupId: project.setups[0].id })
const onBottom = (project: Project): Project => ({ ...project, activeSetupId: BOTTOM_SETUP_ID })

// ── Which setup is simulated ──────────────────────────────────

function testTheFaceDecides(): void {
  console.log('Testing the simulation shows the setup of the face in view...')
  const project = makeProject()
  const top = project.setups[0]
  const topOnly = onTop(project)
  const bottomOnly = onBottom(project)

  assert(activeSetup(topOnly).id === top.id, 'the face in view decides: Top')
  assert(activeSetup(bottomOnly).id === BOTTOM_SETUP_ID, 'and Bottom')

  // The face wins over the selection: with no picker left, a selected
  // operation cannot drag the simulation onto a setup the face is not on.
  const bottomPath = generate(project, 'opBottom')
  const topResult = render(selectedArgs(topOnly, 'opBottom', bottomPath))
  assert(topResult.simulationSetup.id === top.id, 'a selected Bottom operation does not drag the simulation off Top')
  assert(topResult.simulationOperationCount === 0, 'and that operation is not simulated on Top stock')
  assert(topResult.simulationPlaybackInput === null, 'so there is no playback for it there')

  const bottomResult = render(selectedArgs(bottomOnly, 'opBottom', bottomPath))
  assert(bottomResult.simulationSetup.id === BOTTOM_SETUP_ID, 'on Bottom the simulation follows the face as well')
  assert(bottomResult.simulationSetup.name === 'Bottom', 'and names the setup it shows')
  assert(bottomResult.simulationOperationCount === 1, 'simulating the selected Bottom operation')
  assert(bottomResult.simulationSetup.freshStockNote, 'with two setups the fresh-stock note applies')

  // A provisional Bottom the workspace looks at is a listed, empty setup.
  const topNoBottom: Project = {
    ...topOnly,
    setups: [top],
    operations: [project.operations[0]!],
    activeSetupId: provisionalSetupId('bottom'),
  }
  assert(
    JSON.stringify(simulationSetups(topNoBottom).map((setup) => setup.id)) === JSON.stringify([top.id, provisionalSetupId('bottom')]),
    'the provisional Bottom setup is listed after the project\'s own',
  )
  const provisional = render(selectedArgs(topNoBottom, 'opTop', generate(topNoBottom, 'opTop')))
  assert(provisional.simulationSetup.id === provisionalSetupId('bottom'), 'and looked at, it is what the simulation shows')
  assert(provisional.simulationSetup.freshStockNote, 'looking at a second face is a second setup to explain')
}

// ── Selecting an operation puts the workspace on its face ─────

async function testSelectingAnOperationSwitchesTheFace(): Promise<void> {
  console.log('Testing selecting a Bottom operation switches the face and simulates Bottom...')
  const project = makeProject()
  resetStore(onTop(project))
  assert(activeFace(useProjectStore.getState().project) === 'top', 'the fixture starts on Top')

  assert(revealOperationFace('opBottom'), 'selecting a Bottom operation switches the face')
  assert(activeFace(useProjectStore.getState().project) === 'bottom', 'the workspace is on Bottom')
  assert(activeSetup(useProjectStore.getState().project).id === BOTTOM_SETUP_ID, 'and its setup is the simulated one')
  assert(!revealOperationFace('opBottom'), 'selecting again on the face already in view moves nothing')

  // The frame the simulation then builds is the flipped one.
  const switched = useProjectStore.getState().project
  const result = render(selectedArgs(switched, 'opBottom', generate(switched, 'opBottom')))
  assert(result.simulationSetup.id === BOTTOM_SETUP_ID, 'the simulation shows Bottom')
  const grid = (await selectedResult(switched, 'opBottom')).grid
  const local = flipY(centre(BOTTOM_RECT))
  assert(topZAt(grid, local.x, local.y) < STOCK.t - DEPTH * 0.5, 'and cuts the Bottom pocket from the top of the turned stock')

  assert(revealOperationFace('opTop'), 'selecting a Top operation brings Top back')
  assert(activeFace(useProjectStore.getState().project) === 'top', 'the workspace is on Top again')

  // An edit in progress refuses the switch, exactly as a face heading click
  // does: the operation stays selected and the face stays where it is.
  useProjectStore.setState({ selection: { ...useProjectStore.getState().selection, mode: 'sketch_edit' } })
  assert(!revealOperationFace('opBottom'), 'the switch is refused while an edit is in progress')
  assert(activeFace(useProjectStore.getState().project) === 'top', 'so the face has not moved')
  useProjectStore.setState({ selection: { ...useProjectStore.getState().selection, mode: 'feature' } })

  // A dangling setup reference steers nothing.
  const dangling: Project = {
    ...onTop(project),
    operations: [...project.operations, { ...project.operations[1]!, id: 'opGone', setupId: 'gone' }],
  }
  resetStore(dangling)
  assert(!revealOperationFace('opGone'), 'an operation naming a missing setup does not switch the face')
  assert(!revealOperationFace('missing'), 'a missing operation does not switch the face')
  assert(activeFace(useProjectStore.getState().project) === 'top', 'and the face is still Top')
}

// ── The setup follows the face, never a remembered pick ──────

/**
 * Re-render the hook with a different project in the same component instance:
 * the setup it shows must move with the workspace face. A pick kept in state
 * (what the removed picker was) or a setup memoised on the first render would
 * survive the switch, and the simulation would keep showing the face the user
 * left — which is exactly the disagreement this slice removes.
 */
async function testTheSetupIsNotRemembered(): Promise<void> {
  console.log('Testing a face switch moves the hook, with no remembered pick...')
  const project = makeProject()
  const topId = project.setups[0]!.id

  // A DOM for the client render, in place before React DOM is first imported.
  const { parseHTML } = await import('linkedom')
  const { window, document } = parseHTML('<!doctype html><html><body></body></html>')
  const globals = globalThis as unknown as Record<string, unknown>
  globals.window = window
  globals.document = document
  globals.HTMLElement = window.HTMLElement
  globals.Element = window.Element
  globals.Node = window.Node
  if (typeof globals.navigator === 'undefined') {
    globals.navigator = { language: 'en', languages: ['en'], userAgent: 'node', platform: '' }
  }

  let captured: Result | null = null
  function Probe({ face }: { face: Project }) {
    // eslint-disable-next-line react-hooks/globals
    captured = useSimulationModel({
      project: face, centerTab: 'sketch', simulationMode: 'selected', simulationDetailCells: 240,
      selectedOperation: null, selectedToolpath: null, requestToolpath: () => Promise.resolve(null),
    })
    return null
  }
  const shownSetupId = (): string => {
    assert(captured, 'the hook rendered')
    return captured.simulationSetup.id
  }

  const { createRoot } = await import('react-dom/client')
  const { flushSync } = await import('react-dom')
  const host = document.createElement('div')
  document.body.appendChild(host)
  const root = createRoot(host)
  try {
    flushSync(() => root.render(createElement(Probe, { face: onTop(project) })))
    assert(shownSetupId() === topId, 'the first render shows the face it was given (Top)')
    flushSync(() => root.render(createElement(Probe, { face: onBottom(project) })))
    assert(shownSetupId() === BOTTOM_SETUP_ID, 'a face switch moves the simulated setup in the same instance')
    flushSync(() => root.render(createElement(Probe, { face: onTop(project) })))
    assert(shownSetupId() === topId, 'and switching back moves it back')
  } finally {
    flushSync(() => root.unmount())
    host.remove()
  }
}

// ── The hook simulates the setup's frame ─────────────────────

async function testBottomSimulatesLocally(): Promise<void> {
  console.log('Testing a Bottom operation is simulated from the top of the flipped stock...')
  const project = onBottom(makeProject())
  const bottomPath = generate(project, 'opBottom')
  const result = render(selectedArgs(project, 'opBottom', bottomPath))

  assert(result.simulationSetup.id === BOTTOM_SETUP_ID, 'the simulated setup is Bottom')
  assert(result.simulationResult === null, 'the tab-switch render is a loading state')
  const grid = (await selectedResult(project, 'opBottom')).grid
  const local = flipY(centre(BOTTOM_RECT))
  assert(
    topZAt(grid, local.x, local.y) < STOCK.t - DEPTH * 0.5,
    `the Bottom pocket is cut from the top of the flipped stock (Z ${topZAt(grid, local.x, local.y)} at its flipped centre)`,
  )
  const asDrawn = centre(BOTTOM_RECT)
  assert(Math.abs(topZAt(grid, asDrawn.x, asDrawn.y) - STOCK.t) < 1e-6, 'nothing is cut at the unflipped position')
  const topLocal = flipY(centre(TOP_RECT))
  assert(Math.abs(topZAt(grid, topLocal.x, topLocal.y) - STOCK.t) < 1e-6, 'Top\'s pocket is not on Bottom\'s fresh stock')

  const clamp = result.simulationClamps[0]
  const expected = flipY({ x: 14, y: 8 + 4 })
  assert(
    clamp && Math.abs(clamp.x - expected.x) < 1e-9 && Math.abs(clamp.y - expected.y) < 1e-9,
    `the clamp sits where the turned stock puts it (got ${JSON.stringify(clamp)})`,
  )

  // Playback runs the same local motion and starts from fresh stock: Top's
  // cut, listed before it, is not part of Bottom's starting state.
  const playback = result.simulationPlaybackInput
  assert(playback, 'Bottom playback is available')
  assert(playback.moves.every((move) => move.to.z <= STOCK.t + 8 + 1e-9), 'playback moves are setup-local, above the bed')
  assert(playback.moves.some((move) => move.kind === 'cut' && move.to.z > STOCK.t - DEPTH - 1e-9 && move.to.z < STOCK.t), 'and cut down from the top face')
  const base = playback.getBaseGrid()
  assert(Math.abs(topZAt(base, topLocal.x, topLocal.y) - STOCK.t) < 1e-6, 'Top\'s cut is not carried into Bottom playback')
}

async function testTopIsUnchanged(): Promise<void> {
  console.log('Testing a Top face simulates as before...')
  const project = onTop(makeProject())
  const topPath = generate(project, 'opTop')
  const result = render(selectedArgs(project, 'opTop', topPath))
  assert(result.simulationSetup.id === project.setups[0]!.id, 'a Top face simulates Top')
  const grid = (await selectedResult(project, 'opTop')).grid
  const at = centre(TOP_RECT)
  assert(topZAt(grid, at.x, at.y) < STOCK.t - DEPTH * 0.5, 'the Top pocket is cut where it is drawn')
  assert(result.simulationClamps[0]!.x === 14 && result.simulationClamps[0]!.y === 8, 'Top clamps are where they are drawn')
  assert(result.simulationOperationCount === 1, 'one operation is simulated')
}

function testSingleSetupHasNoNote(): void {
  console.log('Testing a single-setup project has nothing to explain...')
  const project = makeProject()
  const single: Project = syncProjectSetups({ ...project, setups: [project.setups[0]!], operations: [project.operations[0]!] })
  const result = render(selectedArgs(single, 'opTop', generate(single, 'opTop')))
  assert(result.simulationSetup.id === single.setups[0]!.id, 'the one setup is the one shown')
  assert(!result.simulationSetup.freshStockNote, 'one setup: no fresh-stock note')
}

testTheFaceDecides()
await testSelectingAnOperationSwitchesTheFace()
await testTheSetupIsNotRemembered()
await testBottomSimulatesLocally()
await testTopIsUnchanged()
testSingleSetupHasNoNote()

console.log('simulation setup model tests passed')

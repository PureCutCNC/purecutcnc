/**
 * The simulation panel's setup wiring (issue #947; one face control since
 * issue #1112 F3): which setup is simulated, and that `useSimulationModel`
 * hands the unchanged heightfield engine that setup's operations in its own
 * frame, on fresh stock.
 *
 * There is one setup choice now — the workspace face control — so the
 * simulation shows the setup of the face in view, and selecting an operation
 * of another face puts the workspace on that face (`revealOperationFace`).
 *
 * The pockets are generated by the shipped generation path and simulated by
 * the shipped engine through the real hook, so a frame or scope the wiring
 * gets wrong shows up as material in the wrong place.
 *
 * Mutations these assertions were checked against, each applied on its own
 * and reverted:
 * - `useSimulationModel` simulating the canonical selected path instead of the
 *   setup input's → "the Bottom pocket is cut from the top of the flipped
 *   stock" fails;
 * - `useSimulationModel` resolving the setup from the selected operation's own
 *   setup instead of the workspace face → "a selected Bottom operation does
 *   not drag the simulation off Top" fails;
 * - `revealOperationFace` not switching the face → "selecting a Bottom
 *   operation switches the face" fails;
 * - `freshStockNote` always true → "a single-setup project has nothing to
 *   explain" fails;
 * - the acquisition asking for every prior operation regardless of setup →
 *   "Bottom playback is available" fails (it waits on a Top path);
 * - `simulationClamps` read from the canonical project → "the clamp sits
 *   where the turned stock puts it" fails.
 *
 * Run with: npx tsx src/app/simulationSetupModel.test.ts
 */


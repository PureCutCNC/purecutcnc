// ── Fresh-stock simulation ────────────────────────────────────

function testFreshStockSimulation(spec: FixtureSpec): void {
  console.log(`Testing fresh-stock Top and Bottom simulation (${spec.units})...`)
  const project = makeProject(spec, 'x')
  const paths = generatePaths(project)
  const topCenter = centerOf(spec.topRect)
  const bottomCenter = centerOf(spec.bottomRect)

  // Top: the pocket opening at the top face is removed from the top down.
  const topResult = replaySetup(buildSimulationSetupInput(project, topSetupOf(project), paths))
  assert(topResult.stats.removedCellCount > 0, 'the Top setup removes material')
  assert(topZAt(topResult.grid, topCenter.x, topCenter.y) < spec.thickness - spec.depth * 0.5, 'the Top pocket is cut at its centre')
  assert(Math.abs(topZAt(topResult.grid, bottomCenter.x, bottomCenter.y) - spec.thickness) < 1e-6, 'the Top pocket does not reach the Bottom pocket')

  for (const axis of ['x', 'y'] as const) {
    // Regenerated for this flip: which way the stock turns changes the
    // generated stock-space path, so reusing the other axis would compare the
    // wrong motion.
    const axisProject = makeProject(spec, axis)
    const axisPaths = generatePaths(axisProject)
    const bottom = bottomSetupOf(axisProject)
    const input = buildSimulationSetupInput(axisProject, bottom, axisPaths)
    const result = replaySetup(input)

    const localBottom = mirrorXY(bottomCenter, axis, spec)
    const localTop = mirrorXY(topCenter, axis, spec)

    assert(result.stats.removedCellCount > 0, `about ${axis}: the Bottom setup removes material`)
    assert(
      topZAt(result.grid, localBottom.x, localBottom.y) < spec.thickness - spec.depth * 0.5,
      `about ${axis}: the Bottom pocket is cut at its flipped position`,
    )
    assert(
      Math.abs(topZAt(result.grid, localTop.x, localTop.y) - spec.thickness) < 1e-6,
      `about ${axis}: the Top pocket's flipped position is untouched on fresh stock`,
    )
    // The cut reaches the pocket floor measured from the top of the flipped stock.
    assert(
      Math.abs(result.stats.minTopZ - (spec.thickness - spec.depth)) <= 2 * result.grid.cellSize,
      `about ${axis}: the Bottom floor is ${spec.thickness - spec.depth} from the flipped top, got ${result.stats.minTopZ}`,
    )

    // In the local frame the Bottom cutter comes down from above the stock.
    const localPath = input.toolpaths.get('opBottom')
    assert(localPath, `about ${axis}: the Bottom path is in the input`)
    const cuts = localPath.moves.filter((move) => move.kind === 'cut' || move.kind === 'plunge')
    assert(cuts.length > 0, `about ${axis}: the Bottom path cuts`)
    for (const move of cuts) {
      assert(
        move.to.z > spec.thickness - spec.depth - 1e-9 && move.to.z <= spec.thickness + 1e-9,
        `about ${axis}: a local cut at Z ${move.to.z} is outside the top ${spec.depth} of the flipped stock`,
      )
    }
  }
}

// ── Export parity ─────────────────────────────────────────────

function bundled(id: string, overrides?: Partial<MachineDefinition>): MachineDefinition {
  const found = BUNDLED_DEFINITIONS.find((definition) => definition.id === id)
  if (!found) throw new Error(`Fixture error: no bundled definition "${id}"`)
  return validateMachineDefinition({ ...structuredClone(found), ...overrides })
}

function testExportParity(spec: FixtureSpec): void {
  console.log(`Testing Bottom simulation motion equals the parsed exported program (${spec.units})...`)
  const project = makeProject(spec, 'x')
  const paths = generatePaths(project)
  const bottom = bottomSetupOf(project)
  const input = buildSimulationSetupInput(project, bottom, paths)
  const operation = input.operations[0]
  const localPath = input.toolpaths.get(operation.id)
  assert(localPath, 'fixture: the Bottom path is in the input')

  // Straight-line moves only: arc fitting legitimately drops the intermediate
  // endpoints of a fitted run, which this comparison would misread as a
  // mismatch rather than a different (valid) way to write the same path.
  const grbl = bundled('grbl')
  const definition = bundled('grbl', { motion: { ...grbl.motion, arcInterpolation: false } })

  const tool = findMillingOperationTool(project, operation)
  assert(tool, 'fixture: the operation has a tool')
  const program = runPostProcessor({
    project,
    definition,
    operations: [{ operation, tool: normalizeToolForProject(tool, project), toolpath: paths.get(operation.id)! }],
    options: { emitToolChanges: true, emitCoolant: false, programName: project.meta.name },
  }).gcode

  const unitsCommand = spec.units === 'inch' ? definition.units.inchCommand : definition.units.mmCommand
  assert(unitsCommand !== null, 'fixture: the definition declares a units command')
  assert(program.includes(unitsCommand), `the program declares ${unitsCommand}`)

  const parsed = parseExportedMotion(program, definition)
  assert(parsed.status === 'verified', `the program parses cleanly, got "${parsed.status}"`)

  const expected = localPath.moves
    .filter((move) => move.kind !== 'rapid')
    .map((move) => projectToMachinePoint(move.to, project.origin, definition))
  const actual = parsed.moves.filter((move) => move.kind !== 'rapid').map((move) => move.to)
  assert(expected.length > 0, 'fixture: the Bottom path has emitted non-rapid motion')
  assert(
    actual.length === expected.length,
    `every local move is emitted: ${actual.length} parsed non-rapid endpoints, expected ${expected.length}`,
  )

  const decimalPlaces = definition.numberFormat.decimalPlaces[spec.units]
  const tolerance = 0.5 * 10 ** -decimalPlaces + 1e-9
  expected.forEach((point, index) => {
    const got = actual[index]
    const matches = Math.abs(got.x - point.x) <= tolerance
      && Math.abs(got.y - point.y) <= tolerance
      && Math.abs(got.z - point.z) <= tolerance
    assert(
      matches,
      `endpoint ${index} is (${got.x}, ${got.y}, ${got.z}), expected (${point.x}, ${point.y}, ${point.z}) within ${tolerance}`,
    )
  })

  // Sanity: the no-arc clone differs from the arc-capable default only in a way
  // this fixture would not accept silently.
  assert(grbl.motion.arcInterpolation === true, 'fixture: the bundled GRBL can interpolate arcs')
}

// ── Drill metadata and cut levels ─────────────────────────────

function testDrillAndLevelMetadataPreserved(): void {
  console.log('Testing drill cycles and pocket levels survive the turn...')
  const project = makeProject(MM)
  const paths = generatePaths(project)
  const bottom = bottomSetupOf(project)
  const input = buildSimulationSetupInput(project, bottom, paths)

  const canonicalPocket = paths.get('opBottom') as PocketToolpathResult
  const localPocket = input.toolpaths.get('opBottom') as PocketToolpathResult
  assert(Array.isArray(canonicalPocket.stepLevels) && canonicalPocket.stepLevels.length > 0, 'fixture: the pocket has cut levels')
  assertEqual(
    localPocket.stepLevels,
    canonicalPocket.stepLevels.map((z) => MM.thickness - z),
    'cut levels are reflected through the stock',
  )

  // A real Bottom drilling operation: the hole, its depths and its peck survive.
  const base = newProject('sim-setup-drill', 'mm')
  base.stock = { ...base.stock, profile: rectProfile(0, 0, 100, 80), thickness: 20 }
  base.origin = { name: 'Origin', x: 0, y: 80, z: 20, visible: true }
  base.tools = [{ ...defaultTool('mm', 1), id: 't1', name: 'Drill 3', type: 'drill', diameter: 3 }]
  const hole: SketchFeature = {
    id: 'hole',
    name: 'hole',
    kind: 'circle',
    folderId: null,
    sketch: {
      profile: circleProfile(20, 15, 3),
      origin: { x: 0, y: 0 },
      orientationAngle: 0,
      dimensions: [],
      constraints: [],
    },
    operation: 'subtract',
    z_top: 8,
    z_bottom: 0,
    authoringFace: 'bottom',
    visible: true,
    locked: false,
  }
  const drill = operation({
    id: 'opDrill',
    name: 'Drill',
    kind: 'drilling',
    drillType: 'peck',
    peckDepth: 2,
    target: { source: 'features', featureIds: ['hole'] },
    setupId: base.activeSetupId,
    stepdown: 2,
  })
  const drillProject = withBottomSetup(
    syncProjectSetups({ ...projectWithFeatures(base, [hole]), operations: [drill] }),
    { axis: 'x', operationIds: ['opDrill'] },
  )
  const drillPaths = generatePaths(drillProject)
  const drillBottom = bottomSetupOf(drillProject)
  const drillInput = buildSimulationSetupInput(drillProject, drillBottom, drillPaths)
  const canonical = drillPaths.get('opDrill')
  const local = drillInput.toolpaths.get('opDrill')
  assert(canonical?.drillCycles && local?.drillCycles, 'fixture: both carry drill cycles')
  assert(canonical.drillCycles.length === local.drillCycles.length, 'one cycle per hole')
  const drillFrame = setupFrame(drillBottom.orientation, drillProject.stock)
  canonical.drillCycles.forEach((cycle, index) => {
    const got = local.drillCycles![index]
    const at = canonicalToSetupPoint({ x: cycle.x, y: cycle.y, z: 0 }, drillFrame)
    assert(Math.abs(got.x - at.x) < 1e-9 && Math.abs(got.y - at.y) < 1e-9, `cycle ${index} is at the flipped position`)
    assert(Math.abs(got.bottomZ - (20 - cycle.bottomZ)) < 1e-9, `cycle ${index} bottom Z is reflected`)
    assert(Math.abs(got.clearZ - (20 - cycle.clearZ)) < 1e-9, `cycle ${index} clearance is reflected`)
    assert(Math.abs(got.retractZ - (20 - cycle.retractZ)) < 1e-9, `cycle ${index} retract is reflected`)
    assert(got.drillType === cycle.drillType && got.peckDepth === cycle.peckDepth, `cycle ${index} keeps its metadata`)
  })
  assert(local !== canonical, 'the drilling path is a turned copy')
}

// ── Stock profile, tabs and clamps ────────────────────────────

function testStockProfileTabsAndClampsAreTurned(): void {
  console.log('Testing the turned frame carries stock profile, tabs and clamps...')
  const project = makeProject(MM)
  const tab: Tab = { id: 'tab', name: 'Tab', x: 30, y: 10, w: 8, h: 6, z_top: 3, z_bottom: 0, visible: true }
  const clamp: Clamp = { id: 'clamp', name: 'Clamp', type: 'step_clamp', x: 90, y: 60, w: 15, h: 20, height: 12, visible: true }
  const notched: Project = {
    ...project,
    stock: {
      ...project.stock,
      profile: polygonProfile([
        { x: 0, y: 0 }, { x: 100, y: 0 }, { x: 100, y: 80 }, { x: 40, y: 80 }, { x: 40, y: 50 }, { x: 0, y: 50 },
      ]),
    },
    tabs: [tab],
    clamps: [clamp],
  }
  const paths = generatePaths(notched)
  const bottom = bottomSetupOf(notched)
  const input = buildSimulationSetupInput(notched, bottom, paths)

  const frame = setupFrame(bottom.orientation, notched.stock)
  const turned = projectInSetupFrame(notched, frame)
  assertEqual(input.project.stock.profile, turned.stock.profile, 'the stock outline is the turned one')

  const toLocal = (point: Point): Point => {
    const mapped = canonicalToSetupPoint({ x: point.x, y: point.y, z: 0 }, frame)
    return { x: mapped.x, y: mapped.y }
  }
  const tabCorner = toLocal({ x: tab.x, y: tab.y + tab.h })
  assertEqual(
    { x: input.project.tabs[0].x, y: input.project.tabs[0].y, w: input.project.tabs[0].w, h: input.project.tabs[0].h },
    { x: tabCorner.x, y: tabCorner.y, w: tab.w, h: tab.h },
    'the tab is placed on the turned stock',
  )
  assertEqual(
    { top: input.project.tabs[0].z_top, bottom: input.project.tabs[0].z_bottom },
    { top: MM.thickness - tab.z_bottom, bottom: MM.thickness - tab.z_top },
    'and its Z span is reflected',
  )
  const clampCorner = toLocal({ x: clamp.x, y: clamp.y + clamp.h })
  assertEqual(
    { x: input.project.clamps[0].x, y: input.project.clamps[0].y, height: input.project.clamps[0].height },
    { x: clampCorner.x, y: clampCorner.y, height: clamp.height },
    'the clamp moves with the stock and keeps its height above the face that is up',
  )
  assert(input.project.origin === notched.origin, 'the shared origin is not turned')
}


function operation(overrides: Partial<Operation> & Pick<Operation, 'kind' | 'target'>): Operation {
  return {
    id: 'op1', name: 'op', pass: 'rough', enabled: true, showToolpath: true, debugToolpath: false,
    toolRef: 't1', stepdown: 2, stepover: 0.4, feed: 800, plungeFeed: 300, rpm: 18000,
    pocketPattern: 'offset', pocketAngle: 0, stockToLeaveRadial: 0, stockToLeaveAxial: 0,
    finishWalls: true, finishFloor: true, carveDepth: 2, maxCarveDepth: 2,
    cutDirection: 'conventional', machiningOrder: 'level_first', ...overrides,
  }
}

function pocketFeature(
  id: string,
  rect: { x: number; y: number; w: number; h: number },
  zTop: number,
  zBottom: number,
  authoringFace: SetupFace,
): SketchFeature {
  return {
    id, name: id, kind: 'rect', folderId: null,
    sketch: {
      profile: rectProfile(rect.x, rect.y, rect.w, rect.h),
      origin: { x: 0, y: 0 }, orientationAngle: 0, dimensions: [], constraints: [],
    },
    operation: 'subtract', z_top: zTop, z_bottom: zBottom,
    authoringFace, visible: true, locked: false,
  }
}

/** A project with one Top pocket and one Bottom pocket, each in its own setup. */
function makeProject(spec: FixtureSpec, axis: Axis = 'x'): Project {
  const base = newProject(`sim-setup-${spec.units}`, spec.units)
  base.meta = { ...base.meta, operationClearanceZ: spec.thickness * 0.4 }
  base.stock = {
    ...base.stock, profile: rectProfile(spec.stockX, spec.stockY, spec.width, spec.height),
    thickness: spec.thickness,
  }
  base.origin = { name: 'Origin', x: spec.stockX, y: spec.stockY + spec.height, z: spec.thickness, visible: true }
  base.tools = [{
    ...defaultTool(spec.units, 1), id: 't1', name: 'Flat endmill',
    diameter: spec.toolDiameter, maxCutDepth: spec.thickness * 2,
  }]
  const features = [
    // A pocket opening at the top face, cut down `depth`.
    pocketFeature('top-pocket', spec.topRect, spec.thickness, spec.thickness - spec.depth, 'top'),
    // A pocket opening at the bottom face, cut up `depth`.
    pocketFeature('bottom-pocket', spec.bottomRect, spec.depth, 0, 'bottom'),
  ]
  const withFeatures = projectWithFeatures(base, features)
  const feed = spec.units === 'inch' ? 30 : 600
  const plungeFeed = spec.units === 'inch' ? 12 : 180
  const shared = {
    kind: 'pocket' as const, toolRef: 't1', setupId: withFeatures.activeSetupId,
    stepdown: spec.depth, stepover: 0.4, feed, plungeFeed,
  }
  const operations: Operation[] = [
    operation({ ...shared, id: 'opTop', name: 'Top pocket', target: { source: 'features', featureIds: ['top-pocket'] } }),
    operation({ ...shared, id: 'opBottom', name: 'Bottom pocket', target: { source: 'features', featureIds: ['bottom-pocket'] } }),
  ]
  const synced = syncProjectSetups({ ...withFeatures, operations })
  return withBottomSetup(synced, { axis, operationIds: ['opBottom'] })
}

function topSetupOf(project: Project) {
  const setup = project.setups.find((entry) => setupFace(entry) === 'top')
  assert(setup, 'fixture: the project has a Top setup')
  return setup
}

function bottomSetupOf(project: Project) {
  const setup = project.setups.find((entry) => entry.id === BOTTOM_SETUP_ID)
  assert(setup, 'fixture: the project has a Bottom setup')
  return setup
}

/** Every operation's generated stock-space result, by id. */
function generatePaths(project: Project): Map<string, ToolpathResult> {
  const paths = new Map<string, ToolpathResult>()
  for (const op of project.operations) {
    const envelope = computeOperationToolpath(project, op)
    assert(envelope, `fixture: ${op.id} is generated`)
    paths.set(op.id, envelope.result)
  }
  return paths
}

/** The consumer's replay: every operation of the setup, into one fresh grid. */
function replaySetup(input: SimulationSetupInput, targetLongAxisCells = 140): SimulationResult {
  const items = input.operations.flatMap((op) => {
    const toolpath = input.toolpaths.get(op.id)
    const tool = findMillingOperationTool(input.project, op)
    if (!toolpath || !tool) return []
    const normalized = normalizeToolForProject(tool, input.project)
    return [{
      operationId: op.id,
      operationName: op.name,
      toolRef: tool.id,
      toolType: tool.type,
      toolRadius: normalized.radius,
      vBitAngle: normalized.vBitAngle,
      toolpath,
    }]
  })
  return simulateReplayItemsHeightfield(input.project, items, { targetLongAxisCells })
}

function topZAt(grid: SimulationGrid, x: number, y: number): number {
  const col = Math.min(grid.cols - 1, Math.max(0, Math.floor((x - grid.originX) / grid.cellSize)))
  const row = Math.min(grid.rows - 1, Math.max(0, Math.floor((y - grid.originY) / grid.cellSize)))
  return grid.topZ[row * grid.cols + col]
}

/** An independent plan mirror — literal arithmetic, not the engine's. */
function mirrorXY(point: Point, axis: Axis, spec: FixtureSpec): Point {
  const cx = spec.stockX + spec.width / 2
  const cy = spec.stockY + spec.height / 2
  return axis === 'x' ? { x: point.x, y: 2 * cy - point.y } : { x: 2 * cx - point.x, y: point.y }
}

function centerOf(rect: { x: number; y: number; w: number; h: number }): Point {
  return { x: rect.x + rect.w / 2, y: rect.y + rect.h / 2 }
}

// ── Scoping, frame and identity ───────────────────────────────

function testTopIsTheSameObjects(): void {
  console.log('Testing a Top input hands back the caller\'s own objects...')
  const project = makeProject(MM)
  const paths = generatePaths(project)
  const input = buildSimulationSetupInput(project, topSetupOf(project), paths)

  assert(input.project === project, 'the project is the same object')
  assert(input.toolpaths.get('opTop') === paths.get('opTop'), 'a Top path is the same object')
  assertEqual(input.operations.map((op) => op.id), ['opTop'], 'a Top input holds only Top operations')
  assertEqual([...input.toolpaths.keys()], ['opTop'], 'and only their paths')
}

function testDisabledAndHiddenOperationsAreIncluded(): void {
  console.log('Testing disabled and hidden operations stay in scope, missing paths stay missing...')
  const project = makeProject(MM)
  const paths = generatePaths(project)
  const top = topSetupOf(project)
  const hidden: Operation = operation({
    id: 'opHidden',
    name: 'Hidden',
    kind: 'pocket',
    target: { source: 'features', featureIds: ['top-pocket'] },
    setupId: top.id,
    enabled: false,
    showToolpath: false,
  })
  const withHidden: Project = { ...project, operations: [...project.operations, hidden] }

  const input = buildSimulationSetupInput(withHidden, top, paths)
  assertEqual(input.operations.map((op) => op.id), ['opTop', 'opHidden'], 'a disabled, hidden operation is still listed')
  assertEqual([...input.toolpaths.keys()], ['opTop'], 'its missing path is not invented')

  // Dropping the acquired path for an in-scope operation keeps it missing.
  const withoutBottom = new Map(paths)
  withoutBottom.delete('opBottom')
  const bottomInput = buildSimulationSetupInput(project, bottomSetupOf(project), withoutBottom)
  assertEqual(bottomInput.operations.map((op) => op.id), ['opBottom'], 'the operation is still listed without its path')
  assert(bottomInput.toolpaths.size === 0, 'and its path is still missing')
}

function testLegacyOperationsReadAsTop(): void {
  console.log('Testing a pre-setup project resolves its operations to Top...')
  const project = makeProject(MM)
  const paths = generatePaths(project)
  const legacy = withoutSetupFields(project) as unknown as Project
  assert(legacy.setups === undefined, 'fixture: the legacy project has no setups')

  const input = buildSimulationSetupInput(legacy, activeSetup(legacy), paths)
  assert(input.project === legacy, 'the legacy project comes back untouched')
  assertEqual(input.operations.map((op) => op.id), ['opTop', 'opBottom'], 'every operation with no setupId reads as Top')
  assertEqual([...input.toolpaths.keys()], ['opTop', 'opBottom'], 'and its paths are the same objects')
  assert(input.toolpaths.get('opTop') === paths.get('opTop'), 'no copy for a Top path')
}

function testBottomIsScopedAndTurned(): void {
  console.log('Testing a Bottom input is scoped to its setup and turned once...')
  const project = makeProject(MM)
  const paths = generatePaths(project)
  const bottom = bottomSetupOf(project)
  const canonicalSnapshot = JSON.stringify({
    stock: project.stock,
    operations: project.operations,
    path: paths.get('opBottom'),
  })

  const input = buildSimulationSetupInput(project, bottom, paths)
  assert(input.project !== project, 'a Bottom project is a turned copy')
  assert(input.project.stock.profile !== project.stock.profile, 'its stock outline is a copy too')
  assertEqual(input.operations.map((op) => op.id), ['opBottom'], 'only the Bottom setup\'s operations')
  assertEqual([...input.toolpaths.keys()], ['opBottom'], 'and only their paths')

  const local = input.toolpaths.get('opBottom')
  const canonical = paths.get('opBottom')
  assert(local && canonical, 'fixture: both paths exist')
  assert(local !== canonical, 'the Bottom path is a turned copy')

  const frame = setupFrame(bottom.orientation, project.stock)
  canonical.moves.forEach((move, index) => {
    const got = local.moves[index]
    const expected = canonicalToSetupPoint(move.to, frame)
    assert(
      Math.abs(got.to.x - expected.x) < 1e-9 && Math.abs(got.to.y - expected.y) < 1e-9 && Math.abs(got.to.z - expected.z) < 1e-9,
      `move ${index}: local (${got.to.x}, ${got.to.y}, ${got.to.z}) is not the stock point turned once`,
    )
  })

  assertEqual(
    JSON.stringify({ stock: project.stock, operations: project.operations, path: paths.get('opBottom') }),
    canonicalSnapshot,
    'the original project, operations and path are not written to',
  )
}

function testProvisionalAndEmptyBottom(): void {
  console.log('Testing a provisional Bottom setup is valid and empty until materialized...')
  const topOnly = makeProject(MM)
  const topOnlyProject: Project = {
    ...topOnly,
    setups: topOnly.setups.filter((entry) => entry.id !== BOTTOM_SETUP_ID),
    operations: topOnly.operations.map((op) => ({ ...op, setupId: topOnly.activeSetupId })),
    activeSetupId: provisionalSetupId('bottom'),
  }
  const paths = generatePaths(topOnlyProject)
  const provisional = activeSetup(topOnlyProject)
  assert(provisional.id === provisionalSetupId('bottom'), 'fixture: the workspace is on a provisional Bottom setup')
  assert(!topOnlyProject.setups.some((entry) => entry.id === provisional.id), 'fixture: it is not one of the project\'s setups')

  const provisionalInput = buildSimulationSetupInput(topOnlyProject, provisional, paths)
  assertEqual(provisionalInput.operations, [], 'a provisional Bottom setup has no operations')
  assert(provisionalInput.toolpaths.size === 0, 'and acquires no paths')
  assert(provisionalInput.project !== topOnlyProject, 'it is still simulated in its turned frame')

  // A real Bottom setup that simply has no operations yet behaves the same.
  const emptyReal = withBottomSetup(topOnlyProject, { axis: 'x' })
  const emptyInput = buildSimulationSetupInput(emptyReal, bottomSetupOf(emptyReal), paths)
  assertEqual(emptyInput.operations, [], 'a materialized but empty Bottom setup has no operations')
  assert(emptyInput.toolpaths.size === 0, 'and no paths')
}


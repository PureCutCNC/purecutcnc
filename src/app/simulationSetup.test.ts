/**
 * One setup's simulation input, end to end (issue #947).
 *
 * The fixtures are real: pockets are generated by the shipped #946 generation
 * path, replayed on fresh stock by the unchanged heightfield engine, and — for
 * a Bottom setup — compared against the program the shipped per-setup exporter
 * emits and a parser reads back. Nothing is stubbed, so a frame this module
 * gets wrong can only show up as motion in the wrong place.
 *
 * Mutations these assertions were checked against, both applied to
 * `simulationSetup.ts` on their own and reverted:
 * - the toolpath turn dropped (`toolpathInSetupFrame` → the input path)
 *   → "Bottom paths are the stock-space paths turned once" and the export
 *   parity fixture fail;
 * - setup membership widened (`(operationSetup ?? topSetup)?.id === setup.id`
 *   → always true) → "Bottom input holds only Bottom operations" fails.
 *
 * Run with: npx tsx src/app/simulationSetup.test.ts
 */


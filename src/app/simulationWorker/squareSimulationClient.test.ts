/**
 * The square-blank simulation worker boundary (issue #1016 C2 P2).
 *
 * The parity case is the accepted square fixture: one real rotary rough
 * generated by the production dispatch on the real default chuck, plus a prior
 * operation whose path is a shallower copy of it, so the starting stock is a
 * real prior replay and replaying every operation instead is visibly different.
 * The worker's handler is called directly (there is no browser Worker in Node)
 * on a `structuredClone` of the job, exactly what the real worker receives, and
 * its result and starting stock are compared with the synchronous functions
 * cell-for-cell.
 *
 * A superseded job is exercised through the hook in a real DOM, with a fake
 * global Worker standing in for the browser's: the delivered result of a job
 * whose inputs have moved must never be shown, and a job that is still running
 * reports pending rather than a stale grid.
 *
 * Mutations checked one at a time against these assertions:
 *  - the worker returning the prior replay as the result → the parity test
 *    fails;
 *  - the starting stock built from all operations instead of the prior ones →
 *    the parity test fails (its fixture guard proves the two replays differ);
 *  - abort not terminating the worker → the abort test fails;
 *  - the stale-job guard removed from the hook → the superseded-job test fails;
 *  - a round fixture routed to the worker → the round/flat test fails.
 *
 * Run with: npx tsx src/app/simulationWorker/squareSimulationClient.test.ts
 */


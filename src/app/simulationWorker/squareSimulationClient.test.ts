function hookArgs(project: Project, operation: Operation, detailCells: number): HookArgs {
  return {
    project,
    centerTab: 'simulation',
    simulationMode: 'selected',
    simulationDetailCells: detailCells,
    selectedOperation: operation,
    selectedToolpath: emptyPath(operation.id),
    requestToolpath: () => Promise.resolve(null),
  }
}

function flatProject(): { project: Project; operation: Operation } {
  const project = newProject('flat worker test', 'mm')
  project.tools = [{ ...defaultTool('mm', 1), id: 't1', type: 'flat_endmill', diameter: 2 }]
  const operation: Operation = {
    ...defaultOperationForTarget(project, 'pocket', 'rough', { source: 'features', featureIds: [] }, 0),
    id: 'op-flat',
    name: 'Flat rough',
  }
  project.operations = [operation]
  return { project, operation }
}

function roundProject(): { project: Project; operation: Operation } {
  const project = newProject('round worker test', 'mm')
  project.meta.projectType = 'rotary'
  project.stock = roundStock(12, 30, 'x')
  project.tools = [{ ...defaultTool('mm', 1), id: 't1', type: 'flat_endmill', diameter: 2 }]
  const operation: Operation = {
    ...defaultOperationForTarget(project, 'pocket', 'rough', { source: 'features', featureIds: [] }, 0),
    id: 'op-round',
    name: 'Round rough',
  }
  project.operations = [operation]
  return { project, operation }
}

/** Mounts with a fake Worker installed, and fails if one is ever constructed. */
async function testRoundAndFlatStaySynchronous(): Promise<void> {
  console.log('Testing round and flat fixtures compute synchronously, with no worker...')
  const globals = globalThis as unknown as { Worker?: unknown }
  const hadWorker = 'Worker' in globals
  const before = FakeSquareWorker.instances.length
  globals.Worker = FakeSquareWorker
  try {
    for (const [label, build] of [['flat', flatProject], ['round', roundProject]] as const) {
      const { project, operation } = build()
      // One stable args object: a fresh `requestToolpath` identity on every
      // render would restart the acquisition effect on every render.
      const args = hookArgs(project, operation, 24)
      let captured: HookResult | null = null
      function Capture() {
        // eslint-disable-next-line react-hooks/globals
        captured = useSimulationModel(args)
        return null
      }
      const mounted = await mountReact(createElement(Capture))
      const result = rendered(() => captured, `${label}: the hook rendered`)
      await mounted.unmount()
      assert.equal(FakeSquareWorker.instances.length, before, `${label}: no worker is created`)
      assert(!result.simulationInputPending, `${label}: the synchronous result is not pending`)
      assert(result.simulationResult !== null, `${label}: the synchronous result is present`)
    }
  } finally {
    if (hadWorker) globals.Worker = FakeSquareWorker
    else delete globals.Worker
  }
}

// ---------------------------------------------------------------------------
// 6. A superseded job's delivered result is never shown for other inputs
// ---------------------------------------------------------------------------

/**
 * A cheap square hook input: no generated path, just enough for the replay to
 * produce the grids the job identity test compares. The test is about which
 * job's answer is shown, not what the answer is.
 */
function cheapSquareArgs(detailCells: number): HookArgs {
  const { project, operation } = squareRotaryProject('x')
  return {
    project,
    centerTab: 'simulation',
    simulationMode: 'selected',
    simulationDetailCells: detailCells,
    selectedOperation: operation,
    selectedToolpath: emptyPath(operation.id),
    requestToolpath: () => Promise.resolve(null),
  }
}

async function testSupersededJobIsDropped(): Promise<void> {
  console.log('Testing a superseded job\'s late result is dropped...')
  const globals = globalThis as unknown as { Worker?: unknown }
  const hadWorker = 'Worker' in globals
  const before = FakeSquareWorker.instances.length
  globals.Worker = FakeSquareWorker
  try {
    const argsA = cheapSquareArgs(24)
    let captured: HookResult | null = null
    let currentArgs = argsA
    function Capture() {
      // eslint-disable-next-line react-hooks/globals
      captured = useSimulationModel(currentArgs)
      return null
    }
    const mounted = await mountReact(createElement(Capture))
    try {
      assert.equal(FakeSquareWorker.instances.length, before + 1, 'the first job starts a worker')
      const workerA = FakeSquareWorker.instances[before]
      const jobA = workerA.posted[0].job
      const deliverableA = runSquareSimulationJob(jobA)
      await act(async () => {
        workerA.deliver({ type: 'result', result: deliverableA.result, startingStock: deliverableA.startingStock })
      })
      const resultA = rendered(() => captured, 'the hook rendered after the first result')
      assert(resultA.simulationResult === deliverableA.result, 'the first job\'s result is shown')
      assert(!resultA.simulationInputPending, 'the first job is no longer pending')

      // Change one job input (the detail resolution). The render that commits
      // this already has the old delivery in state; it must not be shown.
      currentArgs = { ...argsA, simulationDetailCells: 30 }
      await mounted.rerender(createElement(Capture))
      const resultB = rendered(() => captured, 'the hook re-rendered for the new inputs')
      assert(resultB.simulationResult === null, 'the superseded result is not shown for the new inputs')
      assert(resultB.simulationInputPending, 'the new inputs report pending instead')
      assert.equal(workerA.terminated, true, 'superseding terminates the old worker')

      // A result arriving from the aborted worker anyway changes nothing.
      await act(async () => {
        workerA.deliver({ type: 'result', result: deliverableA.result, startingStock: deliverableA.startingStock })
      })
      const resultLate = rendered(() => captured, 'the hook still renders')
      assert(resultLate.simulationResult === null, 'a late result from the superseded job is ignored')

      assert.equal(FakeSquareWorker.instances.length, before + 2, 'the new inputs start a new worker')
      const workerB = FakeSquareWorker.instances[before + 1]
      const deliverableB = runSquareSimulationJob(workerB.posted[0].job)
      await act(async () => {
        workerB.deliver({ type: 'result', result: deliverableB.result, startingStock: deliverableB.startingStock })
      })
      const resultC = rendered(() => captured, 'the hook rendered after the second result')
      assert(resultC.simulationResult === deliverableB.result, 'the latest job\'s result is shown')
      assert(!resultC.simulationInputPending, 'the latest job is no longer pending')
      const playback = resultC.simulationPlaybackInput
      assert(playback, 'the latest job delivers playback')
      assert(
        playback!.getBaseGrid() === deliverableB.startingStock,
        'playback hands back the starting stock the job built',
      )
      assert(playback!.getBaseGrid() === playback!.getBaseGrid(), 'repeated playback calls return the same grid')
    } finally {
      await mounted.unmount()
    }
  } finally {
    if (hadWorker) globals.Worker = FakeSquareWorker
    else delete globals.Worker
  }
}

async function main(): Promise<void> {
  const fixture = await testWorkerParity()
  await testAbortTerminates(fixture.job)
  await testWorkerErrorRejects(fixture.job)
  await testFallback(fixture)
  await testRoundAndFlatStaySynchronous()
  await testSupersededJobIsDropped()
  console.log('square simulation worker tests passed')
}

void main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error)
  throw error
})

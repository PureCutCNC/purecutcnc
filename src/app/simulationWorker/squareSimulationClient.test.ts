function emptyPath(operationId: string): ToolpathResult {
  return { operationId, moves: [], warnings: [], bounds: null }
}

// ---------------------------------------------------------------------------
// The synchronous reference: the pre-worker expressions, written out here so
// a change to the production helpers cannot move both sides of the comparison.
// ---------------------------------------------------------------------------

function referenceOptions(input: SimulationSetupInput): SimulationBuildOptions {
  const frame = input.bar!.frame
  return {
    targetLongAxisCells: DETAIL,
    wrap: { axis: frame.axis === 'x' ? 'y' : 'x', period: frame.circumference },
    squareBar: input.squareBar,
  }
}

function referenceItems(input: SimulationSetupInput, operations: readonly Operation[]): SimulationReplayItem[] {
  return operations
    .filter((operation) => operation.enabled && operation.showToolpath && operation.toolRef)
    .map((operation): SimulationReplayItem | null => {
      const toolpath = input.toolpaths.get(operation.id) ?? null
      const tool = findOperationTool(input.project, operation)
      if (!toolpath || !tool) return null
      const normalized = normalizeToolForProject(tool, input.project)
      return {
        operationId: operation.id,
        operationName: operation.name,
        toolRef: tool.id,
        toolType: tool.type,
        toolRadius: normalized.radius,
        vBitAngle: normalized.vBitAngle,
        toolpath,
      }
    })
    .filter((item): item is SimulationReplayItem => item !== null)
}

function referenceStartingStock(input: SimulationSetupInput, priorCount: number): SimulationGrid {
  return simulateReplayItemsHeightfield(
    input.project,
    referenceItems(input, input.operations.slice(0, priorCount)),
    referenceOptions(input),
  ).grid
}

/** Exact comparison, including every material interval: this is the parity. */
function assertGridsEqual(actual: SimulationGrid, expected: SimulationGrid, label: string): void {
  assert.equal(actual.originX, expected.originX, `${label}: originX`)
  assert.equal(actual.originY, expected.originY, `${label}: originY`)
  assert.equal(actual.cellSize, expected.cellSize, `${label}: cellSize`)
  assert.equal(actual.cols, expected.cols, `${label}: cols`)
  assert.equal(actual.rows, expected.rows, `${label}: rows`)
  assert.equal(actual.stockBottomZ, expected.stockBottomZ, `${label}: stockBottomZ`)
  assert.equal(actual.stockTopZ, expected.stockTopZ, `${label}: stockTopZ`)
  assert.equal(actual.wrap?.axis, expected.wrap?.axis, `${label}: wrap axis`)
  assert.equal(actual.wrap?.period, expected.wrap?.period, `${label}: wrap period`)
  assert.equal(actual.squareBar?.side, expected.squareBar?.side, `${label}: square side`)
  assert.equal(actual.squareBar?.frame.axis, expected.squareBar?.frame.axis, `${label}: frame axis`)
  assert.equal(actual.squareBar?.frame.centre, expected.squareBar?.frame.centre, `${label}: frame centre`)
  assert.equal(actual.squareBar?.frame.radius, expected.squareBar?.frame.radius, `${label}: frame radius`)
  assert.equal(actual.squareBar?.frame.zero, expected.squareBar?.frame.zero, `${label}: frame zero`)
  assert.equal(actual.squareBar?.frame.sheetStart, expected.squareBar?.frame.sheetStart, `${label}: frame sheet start`)
  assert.equal(actual.squareBar?.frame.circumference, expected.squareBar?.frame.circumference, `${label}: frame circumference`)

  assert(actual.topZ instanceof Float32Array, `${label}: topZ is a Float32Array`)
  assert.equal(actual.topZ.length, expected.topZ.length, `${label}: topZ length`)
  for (let index = 0; index < expected.topZ.length; index += 1) {
    assert.equal(actual.topZ[index], expected.topZ[index], `${label}: topZ[${index}]`)
  }

  if (expected.initialTopZ === undefined) {
    assert.equal(actual.initialTopZ, undefined, `${label}: no baseline`)
  } else {
    assert(actual.initialTopZ instanceof Float32Array, `${label}: initialTopZ is a Float32Array`)
    assert.equal(actual.initialTopZ.length, expected.initialTopZ.length, `${label}: initialTopZ length`)
    for (let index = 0; index < expected.initialTopZ.length; index += 1) {
      assert.equal(actual.initialTopZ[index], expected.initialTopZ[index], `${label}: initialTopZ[${index}]`)
    }
  }

  if (expected.squareMaterial === undefined) {
    assert.equal(actual.squareMaterial, undefined, `${label}: no material map`)
    return
  }
  assert(actual.squareMaterial instanceof Map, `${label}: material map survives`)
  assert.equal(actual.squareMaterial.size, expected.squareMaterial.size, `${label}: material cell count`)
  for (const [cell, expectedIntervals] of expected.squareMaterial) {
    const actualIntervals = actual.squareMaterial.get(cell)
    assert(actualIntervals, `${label}: material present for cell ${cell}`)
    assert.equal(actualIntervals.length, expectedIntervals.length, `${label}: cell ${cell} interval count`)
    for (let i = 0; i < expectedIntervals.length; i += 1) {
      assert.equal(actualIntervals[i], expectedIntervals[i], `${label}: cell ${cell} interval ${i}`)
    }
  }
}

function assertStatsEqual(actual: SimulationStats, expected: SimulationStats, label: string): void {
  for (const key of Object.keys(expected) as (keyof SimulationStats)[]) {
    assert.equal(actual[key], expected[key], `${label}: stats.${key}`)
  }
}

/** Read the last rendered hook value, failing if the component never rendered. */
function rendered(read: () => HookResult | null, label: string): HookResult {
  const value = read()
  assert(value, label)
  return value
}

function gridsMatch(left: SimulationGrid, right: SimulationGrid): boolean {
  try {
    assertGridsEqual(left, right, 'compare')
    return true
  } catch {
    return false
  }
}

// ---------------------------------------------------------------------------
// The parity fixture: a real prior operation, then the accepted selected one
// ---------------------------------------------------------------------------

interface ParityFixture {
  job: SquareSimulationJob
  expectedResult: ReturnType<typeof computeSimulationResult>
  expectedStarting: SimulationGrid
}

function parityFixture(): ParityFixture {
  const { project, operation, setup } = squareRotaryProject('x')
  const toolpath = generated(project, operation)
  const priorOperation: Operation = { ...operation, id: 'prior-op', name: 'Prior rough' }
  // The same real path moved 1 mm along the bar: a genuine cut at the same
  // depths over different cells, so "all operations" cannot coincide with
  // "the prior ones".
  const priorPath: ToolpathResult = {
    ...toolpath,
    operationId: priorOperation.id,
    moves: toolpath.moves.map((move) => ({
      ...move,
      from: { ...move.from, x: move.from.x + 1 },
      to: { ...move.to, x: move.to.x + 1 },
    })),
  }
  project.operations = [priorOperation, operation]
  const input = buildSimulationSetupInput(
    project,
    setup,
    new Map([[priorOperation.id, priorPath], [operation.id, toolpath]]),
  )
  assert(input, 'fixture: the around setup yields a simulation input')
  assert.equal(input.operations.length, 2, 'fixture: the setup carries the prior and the selected operation')
  assert(input.squareBar, 'fixture: the input carries the square descriptor')

  const job: SquareSimulationJob = {
    setupInput: input,
    simulationMode: 'selected',
    simulationDetailCells: DETAIL,
    selectedInSetup: operation,
  }
  const expectedResult = computeSimulationResult({
    setupInput: input,
    project,
    simulationMode: 'selected',
    simulationDetailCells: DETAIL,
    selectedInSetup: operation,
    paths: input.toolpaths,
  })
  const expectedStarting = referenceStartingStock(input, 1)
  assert.equal(expectedStarting.squareMaterial!.size > 0, true, 'fixture: the prior operation really cuts')
  assert(
    !gridsMatch(expectedStarting, referenceStartingStock(input, input.operations.length)),
    'fixture: replaying every operation differs from the prior ones, so the mutation is visible',
  )
  return { job, expectedResult, expectedStarting }
}

// ---------------------------------------------------------------------------
// 1. The real worker handler matches the synchronous functions exactly
// ---------------------------------------------------------------------------

async function testWorkerParity(): Promise<ParityFixture> {
  console.log('Testing the worker result and starting stock equal the synchronous functions...')
  const fixture = parityFixture()

  // The real worker receives a structured clone of the job; make sure the job
  // survives it whole rather than trusting that it should.
  const job = structuredClone(fixture.job)
  assert(job.setupInput.toolpaths instanceof Map, 'the toolpath map survives structured clone')
  assert.equal(job.setupInput.operations.length, 2, 'the setup operations survive structured clone')
  assert(job.setupInput.project.stock, 'the setup-local project survives structured clone')
  assert(job.setupInput.squareBar, 'the square descriptor survives structured clone')
  assert(job.selectedInSetup, 'the selected operation survives structured clone')

  const response = handleSquareSimulationMessage({ type: 'run', job })
  if (response.type !== 'result') throw new Error(response.message)

  assertGridsEqual(response.result.grid, fixture.expectedResult.grid, 'worker result grid')
  assertStatsEqual(response.result.stats, fixture.expectedResult.stats, 'worker result')
  assert.equal(response.result.warnings.length, fixture.expectedResult.warnings.length, 'worker result warnings')
  assert(response.startingStock, 'selected mode reports the playback starting stock')
  assertGridsEqual(response.startingStock, fixture.expectedStarting, 'worker starting stock')

  // The heightfields travel by pointer, not copied: both grids' arrays are in
  // the transfer list, and no buffer is listed twice (which would throw).
  const transfer = squareSimulationTransfer(response)
  assert(transfer.includes(response.result.grid.topZ.buffer as ArrayBuffer), 'the result heightfield is transferred')
  assert(
    transfer.includes(response.result.grid.initialTopZ!.buffer as ArrayBuffer),
    'the square baseline is transferred',
  )
  assert(
    transfer.includes(response.startingStock.topZ.buffer as ArrayBuffer),
    'the starting stock heightfield is transferred',
  )
  assert.equal(new Set(transfer).size, transfer.length, 'no buffer is transferred twice')
  return fixture
}

// ---------------------------------------------------------------------------
// 2. Cancellation terminates and rejects; a pre-aborted signal never starts
// ---------------------------------------------------------------------------

class FakeSquareWorker implements SquareSimulationWorkerLike {
  static instances: FakeSquareWorker[] = []

  onmessage: ((event: MessageEvent<SquareSimulationWorkerResponse>) => void) | null = null
  onerror: ((event: ErrorEvent) => void) | null = null
  readonly posted: SquareSimulationWorkerRequest[] = []
  terminated = false

  constructor() {
    FakeSquareWorker.instances.push(this)
  }

  postMessage(message: SquareSimulationWorkerRequest): void {
    this.posted.push(message)
  }

  terminate(): void {
    this.terminated = true
  }

  deliver(response: SquareSimulationWorkerResponse): void {
    this.onmessage?.({ data: response } as MessageEvent<SquareSimulationWorkerResponse>)
  }

  fail(message: string): void {
    this.onerror?.({ message } as ErrorEvent)
  }
}

async function testAbortTerminates(job: SquareSimulationJob): Promise<void> {
  console.log('Testing abort terminates the worker and rejects...')
  const controller = new AbortController()
  const worker = new FakeSquareWorker()
  const promise = runSquareSimulation(job, { signal: controller.signal, createWorker: () => worker })
  assert.equal(worker.posted.length, 1, 'the job is posted before the abort')
  controller.abort()
  await assert.rejects(promise, (error: unknown) => error instanceof SquareSimulationCancelledError)
  assert.equal(worker.terminated, true, 'abort terminates the worker')

  // A result arriving after settlement cannot revive the rejected promise.
  worker.deliver({ type: 'error', message: 'late' })
  assert.equal(worker.terminated, true, 'the settled run stays settled')

  let factories = 0
  await assert.rejects(
    runSquareSimulation(job, {
      signal: AbortSignal.abort(),
      createWorker: () => {
        factories += 1
        return new FakeSquareWorker()
      },
    }),
    (error: unknown) => error instanceof SquareSimulationCancelledError,
  )
  assert.equal(factories, 0, 'an already-aborted signal never starts a worker')
}

// ---------------------------------------------------------------------------
// 3. A worker failure rejects (the hook surfaces it, never an uncut sheet)
// ---------------------------------------------------------------------------

async function testWorkerErrorRejects(job: SquareSimulationJob): Promise<void> {
  console.log('Testing a worker error rejects...')
  const reported = new FakeSquareWorker()
  const reportedPromise = runSquareSimulation(job, { createWorker: () => reported })
  reported.deliver({ type: 'error', message: 'the replay failed' })
  await assert.rejects(reportedPromise, /the replay failed/)
  assert.equal(reported.terminated, true, 'a reported failure terminates the worker')

  const crashed = new FakeSquareWorker()
  const crashedPromise = runSquareSimulation(job, { createWorker: () => crashed })
  crashed.fail('worker crashed')
  await assert.rejects(crashedPromise, /worker crashed/)
  assert.equal(crashed.terminated, true, 'a crash terminates the worker')
}

// ---------------------------------------------------------------------------
// 4. No Worker (Node), or one that cannot be created, runs the same job inline
// ---------------------------------------------------------------------------

async function testFallback(fixture: ParityFixture): Promise<void> {
  console.log('Testing the in-thread fallback gives the same result...')
  assert.equal(typeof (globalThis as { Worker?: unknown }).Worker, 'undefined', 'Node has no Worker')
  const delivered = await runSquareSimulation(fixture.job)
  assertGridsEqual(delivered.result.grid, fixture.expectedResult.grid, 'fallback result grid')
  assertStatsEqual(delivered.result.stats, fixture.expectedResult.stats, 'fallback result')
  assert(delivered.startingStock, 'fallback selected mode reports the starting stock')
  assertGridsEqual(delivered.startingStock, fixture.expectedStarting, 'fallback starting stock')

  // A runtime that has Worker but cannot construct one falls back too.
  const { project, operation } = squareRotaryProject('x')
  const tiny = emptyPath(operation.id)
  const input = buildSimulationSetupInput(project, project.setups[1], new Map([[operation.id, tiny]]))
  assert(input, 'fixture: the cheap around setup yields a simulation input')
  const cheapJob: SquareSimulationJob = {
    setupInput: input,
    simulationMode: 'selected',
    simulationDetailCells: 24,
    selectedInSetup: operation,
  }
  const fallback = await runSquareSimulation(cheapJob, {
    createWorker: () => { throw new Error('worker construction is not available') },
  })
  const expected = runSquareSimulationJob(cheapJob)
  assertGridsEqual(fallback.result.grid, expected.result.grid, 'construction-throws fallback result')
  assert(fallback.startingStock, 'construction-throws fallback still reports the starting stock')
}


/**
 * The internal-vs-exported coverage matrix (issue #1261, slice 1 of #1267).
 *
 * Every operation kind is generated by the real generator on a small project
 * and posted on every bundled definition that can run it — the planar kinds
 * on the router posts, `plasma_profile` on the plasma posts, the rotary kinds
 * on the rotary posts — in a Top and a Bottom setup where the kind has one,
 * in millimetres and inches. Each cell's verdict from `verifyExportedOperation`
 * is asserted against the explicit table below, so any change in a cell is a
 * test diff. A cell that cannot verify is `unverified` with its reason, never
 * skipped. Drilling is one row per drill type, because each one is its own
 * canned cycle.
 *
 * Run with: npx tsx src/engine/gcode/exportParity.matrix.test.ts
 * `MATRIX_PRINT=1` prints the observed table (it is also printed on a
 * mismatch); `MATRIX_DUMP='<row>|<post>|<setup>|<units>'` prints one cell's
 * program, reasons and deviations.
 */


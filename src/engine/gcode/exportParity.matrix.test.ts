const ALL_OK_ROUTER = 'ok ok ok ok ok ok ok'
const ALL_OK_ROTARY = 'ok ok ok ok ok ok'
/** grbl-rotary and grbl-rotary-a are millimetre-only: an inch rotary program is refused (`postRotaryInchUnits`). */
const ROTARY_INCH = 'failed failed ok ok ok ok'
/**
 * Peck (G83) and chip-break (G73) on the canned-cycle posts in inches. Not an
 * exporter fault: the internal toolpath re-enters every peck 0.5 project units
 * above the last depth (`CHIP_BREAK_CLEARANCE` in `toolpaths/drilling.ts` is
 * not unit-aware: 0.5 mm, but 0.5 in = 12.7 mm on an inch project), so it
 * feeds through the air above the retract plane, while the controller's cycle
 * re-enters 0.010 in above the last depth. The hole is the same.
 */
const PECK_INCH = 'ok ok ok DEV DEV DEV ok'

/**
 * `row|setup|units` → one cell per column, in column order. Router rows are
 * generic, grbl, grblhal, mach3, uccnc, linuxcnc, shopbot; plasma rows
 * qtplasmac, grbl-plasma; rotary rows the six rotary posts in table order.
 */
const EXPECTED: Record<string, string> = {}
for (const units of ['mm', 'inch'] as const) {
  for (const face of ['top', 'bottom'] as const) {
    for (const row of PLANAR_ROWS) {
      const peck = row === 'drilling:peck' || row === 'drilling:chip_breaking'
      EXPECTED[`${row}|${face}|${units}`] = peck && units === 'inch' ? PECK_INCH : ALL_OK_ROUTER
    }
  }
}
Object.assign(EXPECTED, {
  // QtPlasmaC owns the torch height and the cut feed (`F#<_hal[...]>`, the
  // `#<holes>` parameter, no Z word at all): the reader cannot reconstruct
  // either, so it does not claim the program. Plasma is Top-only: a Bottom
  // plasma operation generates no motion.
  'plasma_profile|top|mm': 'unsupported ok',
  'plasma_profile|bottom|mm': 'unsupported nocut',
  'plasma_profile|top|inch': 'unsupported ok',
  'plasma_profile|bottom|inch': 'unsupported nocut',
  'rotary_rough|around-x|mm': ALL_OK_ROTARY,
  'rotary_rough|around-y|mm': ALL_OK_ROTARY,
  'rotary_rough|around-x|inch': ROTARY_INCH,
  'rotary_finish|around-x|mm': ALL_OK_ROTARY,
  'rotary_finish|around-y|mm': ALL_OK_ROTARY,
  'rotary_finish|around-x|inch': ROTARY_INCH,
  'pocket:wrapped|around-x|mm': ALL_OK_ROTARY,
  'pocket:wrapped|around-x|inch': ROTARY_INCH,
  'follow_line:wrapped|around-x|mm': ALL_OK_ROTARY,
  'follow_line:wrapped|around-x|inch': ROTARY_INCH,
})

// Every operation kind has at least one row.
const KINDS: Record<OperationKind, true> = {
  plasma_profile: true, pocket: true, v_carve: true, v_carve_medial: true, edge_route_inside: true,
  edge_route_outside: true, surface_clean: true, rotary_rough: true, rotary_finish: true, rough_surface: true,
  finish_surface: true, finish_surface_cleanup: true, follow_line: true, drilling: true,
}
for (const kind of Object.keys(KINDS)) {
  assert(Object.keys(EXPECTED).some((key) => key.split('|')[0].split(':')[0] === kind), `${kind} has a row in the table`)
}

const actualRows = new Map<string, Cell[]>()
for (const [key, cell] of observed) {
  const [row, , setup, units] = key.split('|')
  const line = `${row}|${setup}|${units}`
  actualRows.set(line, [...(actualRows.get(line) ?? []), cell])
}
const mismatches: string[] = []
for (const [line, expected] of Object.entries(EXPECTED)) {
  const actual = actualRows.get(line)?.join(' ')
  if (actual !== expected) mismatches.push(`${line}: expected '${expected}', got '${actual ?? 'no cells'}'`)
}
for (const line of actualRows.keys()) {
  if (!(line in EXPECTED)) mismatches.push(`${line}: observed but not in the table`)
}

if (PRINT || mismatches.length > 0) {
  for (const [line, cells] of actualRows) console.log(`  '${line}': '${cells.join(' ')}',`)
  for (const [key, detail] of details) console.log('  ', key, detail)
  console.log(`elapsed ${Date.now() - started} ms`)
}
assert(mismatches.length === 0, `the matrix changed:\n${mismatches.join('\n')}`)
console.log(`exportParity matrix: ${observed.size} cells match the table (${Date.now() - started} ms)`)

// ── Fixtures ──────────────────────────────────────────────────

/** Every length below is millimetres; `len` puts it in the project's units. */
function lengths(units: Units) {
  return (mm: number) => convertLength(mm, 'mm', units)
}

function feature(
  id: string,
  profile: SketchProfile,
  zTop: number,
  zBottom: number,
  face: SetupFace,
  kind: SketchFeature['kind'] = 'rect',
): SketchFeature {
  return {
    id, name: id, kind, folderId: null,
    sketch: { profile, origin: { x: 0, y: 0 }, orientationAngle: 0, dimensions: [], constraints: [] },
    operation: 'subtract', z_top: zTop, z_bottom: zBottom,
    authoringFace: face, visible: true, locked: false,
  }
}

function openLine(points: Array<{ x: number; y: number }>): SketchProfile {
  return {
    start: points[0],
    segments: points.slice(1).map((to) => ({ type: 'line' as const, to })),
    closed: false,
  }
}

/** A small closed wedge for the 3D kinds, in the fixture's units. */
function wedgeMesh(len: (mm: number) => number, x0: number, y0: number, zLow: number, zHigh: number) {
  const raw = [
    0, 0, 0, 16, 0, 0, 16, 10, 0, 0, 10, 0,
    0, 0, 1, 16, 0, 1, 16, 10, 1, 0, 10, 1,
  ]
  const positions = new Float32Array(raw.length)
  for (let i = 0; i < raw.length; i += 3) {
    positions[i] = len(x0 + raw[i])
    positions[i + 1] = len(y0 + raw[i + 1])
    // The top face slopes from zLow at x0 to zHigh at x0 + 16.
    const top = zLow + (zHigh - zLow) * (raw[i] / 16)
    positions[i + 2] = len(raw[i + 2] === 0 ? 0 : top)
  }
  const index = new Uint32Array([0, 2, 1, 0, 3, 2, 4, 5, 6, 4, 6, 7, 0, 1, 5, 0, 5, 4, 1, 2, 6, 1, 6, 5, 2, 3, 7, 2, 7, 6, 3, 0, 4, 3, 4, 7])
  return { positions, index, bounds: computeMeshBounds(positions) }
}

const STOCK = { w: 60, h: 40, t: 12 }

/** Kinds cut in a Top or Bottom setup, and drilling per drill type. */
type PlanarRow = Exclude<OperationKind, 'plasma_profile' | 'rotary_rough' | 'rotary_finish' | 'drilling'>
  | `drilling:${DrillType}`

const PLANAR_ROWS: PlanarRow[] = [
  'pocket', 'edge_route_inside', 'edge_route_outside', 'v_carve', 'v_carve_medial', 'follow_line',
  'surface_clean', 'rough_surface', 'finish_surface', 'finish_surface_cleanup',
  'drilling:simple', 'drilling:peck', 'drilling:dwell', 'drilling:chip_breaking', 'drilling:helical', 'drilling:countersink',
]

/**
 * One project per face and unit system holding a feature for every kind. The
 * Bottom project authors the same features on the bottom face (depths measured
 * up from the stock bottom) and moves every operation into a Bottom setup.
 */
function planarProject(units: Units, face: 'top' | 'bottom'): { project: Project; operations: Map<PlanarRow, Operation> } {
  const len = lengths(units)
  const base = newProject(`parity-${units}-${face}`, units)
  base.meta.created = base.meta.modified = '2026-01-01T00:00:00.000Z'
  base.stock = { ...base.stock, profile: rectProfile(0, 0, len(STOCK.w), len(STOCK.h)), thickness: len(STOCK.t) }
  base.origin = { name: 'Origin', x: 0, y: len(STOCK.h), z: len(STOCK.t), visible: true }
  const tool = (id: string, extra: Partial<Tool>): Tool => ({
    ...defaultTool(units, 1), id, name: id,
    diameter: len(3), defaultStepdown: len(2), defaultStepover: 0.4,
    defaultFeed: len(800), defaultPlungeFeed: len(250), maxCutDepth: len(20),
    ...extra,
  })
  base.tools = [
    tool('flat', { type: 'flat_endmill' }),
    tool('vbit', { type: 'v_bit', diameter: len(6), vBitAngle: 90 }),
    tool('ball', { type: 'ball_endmill', diameter: len(2), defaultStepover: 0.3 }),
    tool('drill', { type: 'drill', diameter: len(2.5) }),
  ]
  // Depth into the stock from the face, as stock-space Z spans.
  const top = len(STOCK.t)
  const span = (depth: number): [number, number] => face === 'top' ? [top, top - len(depth)] : [len(depth), 0]
  const hole = (id: string, cx: number, cy: number, r: number, depth: number) =>
    feature(id, circleProfile(len(cx), len(cy), len(r)), ...span(depth), face, 'circle')
  const features: SketchFeature[] = [
    feature('pocket', rectProfile(len(4), len(4), len(14), len(10)), ...span(3), face),
    feature('ring', circleProfile(len(30), len(10), len(5)), ...span(2), face, 'circle'),
    hole('vc', 48, 9, 4, 2),
    feature('line', openLine([{ x: len(4), y: len(20) }, { x: len(20), y: len(24) }, { x: len(26), y: len(20) }]), ...span(1), face, 'polygon'),
    hole('d1', 6, 33, 1.25, 5),
    hole('d2', 12, 33, 1.25, 5),
    hole('bore', 20, 33, 2.5, 4),
    // A boss standing 1 mm proud of a 2 mm deep floor: edge outside and surface clean.
    { ...feature('boss', circleProfile(len(28), len(32), len(4)), ...(face === 'top' ? [top - len(1), top - len(3)] as [number, number] : [len(3), len(1)] as [number, number]), face, 'circle'), operation: 'add' },
  ]
  // The 3D model: a wedge standing in a 2 mm deep pocket of the face.
  base.modelAssets = { wedge: serializeImportedMesh(wedgeMesh(len, 36, 22, 6, 10), 'stl') }
  features.push({
    id: 'model', name: 'Model', kind: 'stl', operation: 'model', authoringFace: face, folderId: null,
    sketch: { profile: rectProfile(len(36), len(22), len(16), len(10)), origin: { x: 0, y: 0 }, orientationAngle: 0, dimensions: [], constraints: [] },
    stl: { format: 'stl', meshAssetId: 'wedge', scale: 1, axisSwap: 'none' },
    z_top: face === 'top' ? len(STOCK.t) : len(STOCK.t - 6), z_bottom: face === 'top' ? len(6) : 0, visible: true, locked: false,
  })
  const withFeatures = projectWithFeatures(base, features)

  const operations = new Map<PlanarRow, Operation>()
  const make = (row: PlanarRow, kind: OperationKind, targetIds: string[] | null, toolRef: string, extra: Partial<Operation> = {}) => {
    const target = targetIds === null ? { source: 'stock' as const } : { source: 'features' as const, featureIds: targetIds }
    const operation: Operation = {
      ...defaultOperationForTarget(withFeatures, kind, kind.startsWith('finish') ? 'finish' : 'rough', target, operations.size),
      id: `op-${row.replace(':', '-')}`,
      name: row,
      toolRef,
      setupId: withFeatures.activeSetupId,
      feed: len(800),
      plungeFeed: len(250),
      stepdown: len(1.5),
      ...extra,
    }
    operations.set(row, operation)
  }
  make('pocket', 'pocket', ['pocket'], 'flat')
  make('edge_route_inside', 'edge_route_inside', ['ring'], 'flat')
  make('edge_route_outside', 'edge_route_outside', ['boss'], 'flat')
  make('v_carve', 'v_carve', ['vc'], 'vbit')
  make('v_carve_medial', 'v_carve_medial', ['vc'], 'vbit')
  make('follow_line', 'follow_line', ['line'], 'flat', { carveDepth: len(1) })
  make('surface_clean', 'surface_clean', ['boss'], 'flat', { stepdown: len(0.5) })
  make('rough_surface', 'rough_surface', ['model'], 'flat', { stepdown: len(2) })
  make('finish_surface', 'finish_surface', ['model'], 'ball', { stepover: 0.5 })
  make('finish_surface_cleanup', 'finish_surface_cleanup', ['model'], 'ball', { stepover: 0.5 })
  for (const drillType of ['simple', 'peck', 'dwell', 'chip_breaking', 'helical', 'countersink'] as const) {
    const toolRef = drillType === 'helical' ? 'flat' : drillType === 'countersink' ? 'vbit' : 'drill'
    make(`drilling:${drillType}`, 'drilling', drillType === 'helical' ? ['bore'] : ['d1', 'd2'], toolRef, {
      drillType, peckDepth: len(1.5), dwellTime: 0.5,
    })
  }
  assert(
    JSON.stringify([...operations.keys()]) === JSON.stringify(PLANAR_ROWS),
    'the fixture makes one operation per planar row, in table order',
  )
  let project = syncProjectSetups({ ...withFeatures, operations: [...operations.values()] })
  if (face === 'bottom') {
    project = withBottomSetup(project, { operationIds: [...operations.values()].map((operation) => operation.id) })
    for (const [row, operation] of operations) {
      operations.set(row, project.operations.find((candidate) => candidate.id === operation.id)!)
    }
  }
  return { project, operations }
}

// ── Definitions ───────────────────────────────────────────────

function validated(definition: MachineDefinition): MachineDefinition {
  return validateMachineDefinition(structuredClone(definition))
}

const ROUTERS = BUNDLED_DEFINITIONS
  .filter((definition) => resolveMachineKind(definition) === 'router' && definition.rotary === undefined)
  .map(validated)
const PLASMAS = BUNDLED_DEFINITIONS.filter((definition) => resolveMachineKind(definition) === 'plasma').map(validated)
const ROTARIES = BUNDLED_ROTARY_DEFINITIONS.map(validated)

// ── Running a cell ────────────────────────────────────────────

/**
 * A cell, as the table spells it: `ok` (verified), `DEV` (deviation), or the
 * unverified reason — `unsupported` (the program has a construct the reader
 * cannot reconstruct), `failed` (no program, or the post refused the
 * operation), `nocut` (neither path has a feed move).
 */
type Cell = 'ok' | 'DEV' | 'unsupported' | 'failed' | 'nocut'

function cellOf(parity: ExportParityResult): Cell {
  switch (parity.verdict) {
    case 'verified': return 'ok'
    case 'deviation': return 'DEV'
    case 'unverified':
      return parity.reason === 'exportUnsupported' ? 'unsupported' : parity.reason === 'exportFailed' ? 'failed' : 'nocut'
  }
}

const observed = new Map<string, Cell>()
const details = new Map<string, string>()

function run(key: string, project: Project, operation: Operation, toolpath: ToolpathResult, definition: MachineDefinition): void {
  const { motion, parity } = verifyExportedOperation({ project, operation, toolpath, definition })
  if (process.env.MATRIX_DUMP === key) {
    console.log(motion.program)
    console.log(JSON.stringify(motion.reasons))
    console.log(JSON.stringify(parity.deviations, null, 1))
  }
  const cell = cellOf(parity)
  observed.set(key, cell)
  // A verified cell compared real motion, both ways.
  if (cell === 'ok') {
    assert(parity.samples.internal > 0 && parity.samples.exported > 0, `${key}: a verified cell sampled both paths`)
  }
  if (cell !== 'ok') {
    details.set(key, JSON.stringify({
      reasons: motion.reasons.filter((reason) => reason.severity !== 'info').map((reason) => `${reason.code}${reason.command ? `(${reason.command})` : ''}`),
      post: motion.postWarnings.map((warning) => warning.code),
      deviations: parity.deviations.slice(0, 3).map((deviation) => `${deviation.kind}@${deviation.distance.toFixed(4)}`),
      count: parity.deviationCount,
    }))
  }
}

const started = Date.now()

for (const units of ['mm', 'inch'] as const) {
  for (const face of ['top', 'bottom'] as const) {
    const { project, operations } = planarProject(units, face)
    for (const [row, operation] of operations) {
      const envelope = computeOperationToolpath(project, operation)
      assert(envelope, `${row} ${face} ${units}: the generator handles the kind`)
      const toolpath = envelope.result
      if (PRINT && toolpath.moves.length === 0) console.log(`  (fixture) ${row} ${face} ${units}: no moves ${JSON.stringify(toolpath.warnings)}`)
      for (const definition of ROUTERS) {
        run(`${row}|${definition.id}|${face}|${units}`, project, operation, toolpath, definition)
      }
    }
  }
}

// ── Plasma ────────────────────────────────────────────────────

function plasmaProject(units: Units, face: 'top' | 'bottom'): { project: Project; operation: Operation } {
  const len = lengths(units)
  const base = newProject(`parity-plasma-${units}-${face}`, units)
  base.meta.created = base.meta.modified = '2026-01-01T00:00:00.000Z'
  base.stock = { ...base.stock, profile: rectProfile(0, 0, len(120), len(80)), thickness: len(2) }
  base.origin = { name: 'Origin', x: 0, y: len(80), z: len(2), visible: true }
  base.tools = [{ ...defaultPlasmaTool(units), id: 'torch', name: 'Torch', qtplasmacMaterialNumber: 1 }]
  const sheet = (id: string, operation: SketchFeature['operation'], profile: SketchProfile): SketchFeature => ({
    ...feature(id, profile, len(2), 0, face), operation,
  })
  const project0 = projectWithFeatures(base, [
    sheet('plate', 'add', rectProfile(len(10), len(10), len(60), len(40))),
    sheet('hole', 'subtract', circleProfile(len(40), len(30), len(8))),
  ])
  const operation: Operation = {
    ...defaultOperationForTarget(project0, 'plasma_profile', 'rough', { source: 'features', featureIds: ['hole', 'plate'] }, 0),
    id: 'op-plasma', name: 'plasma', toolRef: 'torch', setupId: project0.activeSetupId,
  }
  let project = syncProjectSetups({ ...project0, operations: [operation] })
  if (face === 'bottom') project = withBottomSetup(project, { operationIds: [operation.id] })
  return { project, operation: project.operations[0] }
}

for (const units of ['mm', 'inch'] as const) {
  for (const face of ['top', 'bottom'] as const) {
    const { project, operation } = plasmaProject(units, face)
    const envelope = computeOperationToolpath(project, operation)
    assert(envelope, `plasma ${face} ${units}: generated`)
    for (const definition of PLASMAS) {
      run(`plasma_profile|${definition.id}|${face}|${units}`, project, operation, envelope.result, definition)
    }
  }
}

